import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve, posix, win32 } from "node:path";
import test from "node:test";
import { build } from "esbuild";
import { captureOwnedRuntimeInputs, runtimePathIdentity } from "../src/rpc-runtime-inputs";

test("runtime path identities normalize Windows filesystem spellings but not import specifiers or sibling roots", () => {
  const identity = runtimePathIdentity("D:\\work\\package", "D:\\work\\package", win32);
  assert.equal(identity("D:/work/package/.sunder/generated/rpc/worker.ts"), identity("D:\\work\\package\\.sunder\\generated\\rpc\\worker.ts"));
  assert.equal(identity("d:/work/package/src/../src/service.ts"), "D:\\work\\package\\src\\service.ts");
  assert.notEqual(identity("D:/work/package-other/src/service.ts"), identity("D:/work/package/src/service.ts"));
  assert.notEqual(identity("E:/work/package/src/service.ts"), identity("D:/work/package/src/service.ts"));
  assert.notEqual(identity("D:/work/package/src/Service.ts"), identity("D:/work/package/src/service.ts"));
  for (const specifier of ["", "./service.js", "../service.js", "pkg/service", "#sunder/api", "node:fs", "sunder-owned-rpc:adapter", "owned/service.ts", "D:service.ts"]) {
    assert.equal(identity(specifier), specifier);
  }
  const unc = runtimePathIdentity("\\\\server\\share\\package", "\\\\server\\share\\package", win32);
  assert.equal(unc("//server/share/package/src/service.ts"), unc("\\\\server\\share\\package\\src\\service.ts"));
});

test("runtime path identities alias only the captured project root and preserve POSIX case and backslashes", () => {
  const identity = runtimePathIdentity("/var/work/package", "/private/var/work/package", posix);
  assert.equal(identity("/var/work/package/src/service.ts"), identity("/private/var/work/package/src/service.ts"));
  assert.equal(identity("/var/work/package-other/src/service.ts"), "/var/work/package-other/src/service.ts");
  assert.notEqual(identity("/var/work/package/src/Service.ts"), identity("/var/work/package/src/service.ts"));
  assert.notEqual(identity("/var/work/package/src\\service.ts"), identity("/var/work/package/src/service.ts"));
  assert.equal(identity("./service.js"), "./service.js");
});

test("cold and materialized runtime replay share filesystem identities without admitting uncaptured resolutions", async () => {
  const root = await mkdtemp(resolve(tmpdir(), "sunder-runtime-inputs-"));
  try {
    await mkdir(resolve(root, "src"));
    const modulePath = resolve(root, "src/service.ts");
    await writeFile(modulePath, "export const value = 42;");
    const entry = resolve(root, ".sunder/generated/rpc/worker.ts");
    const generated = new Map([["worker.ts", `import { value } from ${JSON.stringify(modulePath.replaceAll("\\", "/").replace(/\.ts$/u, ".js"))}; module.exports = value;`]]);
    // rpc-authoring supplies slash paths; package.ts supplies native paths.
    const captured = await captureOwnedRuntimeInputs(root, entry.replaceAll("\\", "/"), modulePath, "", "", generated);
    assert.deepEqual(captured.sourceFiles, [modulePath.replaceAll("\\", "/")]);
    const replay = (path: string) => build({ absWorkingDir: root, entryPoints: [path], bundle: true, platform: "node", format: "cjs", tsconfigRaw: {},
      write: false, logLevel: "silent", plugins: [captured.plugin(async () => {})] });
    for (const materialized of [false, true]) {
      if (materialized) {
        await mkdir(resolve(root, ".sunder/generated/rpc"), { recursive: true });
        await writeFile(entry, 'throw new Error("uncaptured generated bytes");');
      }
      await captured.revalidate();
      const result = await replay(entry);
      const module = { exports: undefined as unknown };
      new Function("module", result.outputFiles[0]!.text)(module);
      assert.equal(module.exports, 42);
    }
    // Even an existing file under the same root cannot fall back to filesystem
    // resolution. No validation callback is needed for this replay-only guard.
    const other = resolve(root, "src/uncaptured.ts");
    await writeFile(other, "module.exports = 99;");
    await assert.rejects(replay(other), /uncaptured runtime resolution/);
  } finally { await rm(root, { recursive: true, force: true }); }
});
