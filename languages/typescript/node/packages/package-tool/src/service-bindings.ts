import { authoringBindingModel } from "@sunder/sdk";
import { createHash } from "node:crypto";
import type { LoadedContract } from "./model";
import { contractSymbol, type PackageImportAnalysis } from "./rpc-package-imports";
import { camel, pascal, importedProviderMethodNames, type SourceService } from "./service-source";
import { coalesceRoleUses,roleUsesOuter } from "./rpc-owned-uses";

export function serviceApiSource(owner: string, contracts: readonly LoadedContract[], services: readonly SourceService[], imports: PackageImportAnalysis, packageVersion: string, sourceTypes = true): string {
  const modules = new Map(contracts.map((contract, index) => [contract.contractKey!, `$binding${index}`]));
  const lines = ['// <auto-generated />', 'import { createApiToken, createServiceContract, createServiceToken, createServiceCatalog } from "@sunder/sdk/browser";', 'import type { ApiToken, ApiIdentity, ApiBindingContext, RpcCallOptions, ServiceContext, ServiceContract, ServiceStream, ServiceToken, ServiceCatalog, ServiceProvider, ServiceReference, SunderContent, ServiceDomainError } from "@sunder/sdk/browser";'];
  const serviceFactories=new Map<string,{factory:string;token:string}>();const serviceDefinitions:string[]=[];
  for (const contract of contracts) lines.push(`import * as ${modules.get(contract.contractKey!)} from "./${contract.imported ? "imported/" : "owned/"}${contract.contractKey!}.js";`);
  function members(selected: readonly LoadedContract[], packageId: string, imported = false, range?: string, prerelease?: boolean, tokensOnly=false, contractScoped=false): string {
    const result = new Map<string, string>();
    const names = new Map<string, string>();
    const add = (scope: Map<string, string>, key: string, origin: string): void => {
      const normalized = key.toLowerCase(); const previous = scope.get(normalized);
      if (previous !== undefined) throw new Error(`rpc-authoring.generated-name-collision: '${previous}' and '${origin}' normalize to '${key}' in the same API scope of package '${packageId}'.`);
      scope.set(normalized, origin);
    };
    for (const contract of selected) {
      const model = authoringBindingModel(contract.descriptor); const module = modules.get(contract.contractKey!)!;
      // Only Self has source parameter metadata. External projection cannot infer
      // the producer language's argument list (including an empty request/void).
      const authored = imported ? undefined : services.find(service => service.key === contract.contractKey && !service.importKey);
      // Package roots always supply a contract scope. Services.Contracts already
      // supplies that scope, while Self keeps its ordinary authored shape.
      const scope = contractScoped ? contractScope(contract.descriptor.contractId) : undefined;
      if (scope !== undefined) add(names, scope, contract.descriptor.contractId);
      const serviceNames = contractScoped ? new Map<string, string>() : names;
      const serviceMembers: string[] = [];
      for (const service of model.services) {
        const key = authored ? camel(authored.key) : lowerInitial(service.clientPropertyName);
        add(serviceNames, key, `${contract.descriptor.contractId}/${service.descriptor.serviceId}`);
        const identity = JSON.stringify({ packageId, contractId: contract.descriptor.contractId, contractVersion: contract.descriptor.version, descriptorSha256: contract.descriptorSha256, abiSha256: contract.abiSha256,
          ...(range === undefined ? {} : { packageRange: range, includePrerelease: prerelease }) });
        const serviceKey=contract.descriptor.contractId+"/"+service.descriptor.serviceId;
        let generatedService=serviceFactories.get(serviceKey);
        if(!generatedService){
        const methods: string[] = [];
        for (const method of service.methods) {
          const source = authored?.methods.find(candidate => candidate.wireName === method.descriptor.methodId && candidate.serviceId === service.descriptor.serviceId);
          const requestRef = method.descriptor.requestSchema; const resultRef = method.descriptor.kind === "unary" ? method.descriptor.responseSchema! : method.descriptor.eventSchema!;
          const type = (ref: typeof requestRef): string => `${module}.${model.definitionNames.get((typeof ref === "string" ? ref : ref.$ref).slice("#/$defs/".length))!}`;
          const args = source?.parameters ?? [{ name: "request", optional: false }];
          const direct = !source || source.directRequest;
          const parameters = args.map(argument => `${argument.name}${argument.optional ? "?" : ""}: ${direct ? type(requestRef) : `${type(requestRef)}[${JSON.stringify(argument.name)}]`}`);
          const request = direct ? args[0]!.name : `{${args.map(argument => argument.optional ? `...(${argument.name} === undefined ? {} : {${argument.name}})` : argument.name).join(",")}}`;
          const contentIdentity=carriesContent(requestRef,contract.descriptor.$defs)||carriesContent(resultRef,contract.descriptor.$defs)||(method.descriptor.errors??[]).some(code=>carriesContent(contract.descriptor.errors[code]?.detailsSchema,contract.descriptor.$defs))
             ? `{...identity,${contract.naturalContent?"resourceContent":"callerOwnedContent"}:true}`:"identity";
          const timeout=contract.methodPolicies?.[service.descriptor.serviceId]?.[method.descriptor.methodId]?.timeoutSeconds;
          const methodIdentity=timeout===undefined?contentIdentity:`{...${contentIdentity},timeoutSeconds:${timeout}}`;
          const operation = method.descriptor.kind === "unary" ? "unary" : "stream";
          if(source?.name==="Providers")throw new Error("rpc-authoring.generated-name-collision: 'Providers' is reserved for the generated service catalog.");
          const returnType = source?.unit ? "void" : type(resultRef);
          const invocation = `new ${module}.${model.clientFacadeTypeName}(transport, target${hasServiceResources(contract)?", resources":""}).${service.clientPropertyName}.${method.methodName}(${request}, linked)`;
          methods.push(`${JSON.stringify(source?.name??lowerInitial(method.methodName))}(${[...parameters, "$options?: RpcCallOptions"].join(", ")}): ${operation === "unary" ? `Promise<${returnType}>` : `ServiceStream<${returnType}>`} { return context.${operation}(${methodIdentity}, (transport, target, linked, resources) => ${invocation}${source?.unit && operation === "unary" ? ".then(() => undefined)" : ""}, $options); }`);
        }
        const factory=`$createService${serviceFactories.size}`;const token=`$serviceToken${serviceFactories.size}`;
        const target={contractId:contract.descriptor.contractId,contractVersion:contract.descriptor.version,descriptorSha256:contract.descriptorSha256,abiSha256:contract.abiSha256,serviceId:service.descriptor.serviceId};
        serviceDefinitions.push(`function ${factory}(context:ApiBindingContext,identity:ApiIdentity){return Object.freeze({${methods.join(",\n")}});}`,
          `const ${token}: ServiceToken<ReturnType<typeof ${factory}>> & {readonly contractId:${JSON.stringify(target.contractId)};readonly serviceId:${JSON.stringify(target.serviceId)}} = createServiceToken(${JSON.stringify(target)} as const,context=>${factory}(context,${identity}));`,
          `export type ${serviceTokenTypeName(target.contractId,target.serviceId)} = typeof ${token};`);
        generatedService={factory,token};serviceFactories.set(serviceKey,generatedService);
        }
        const member = `${JSON.stringify(key)}: ${tokensOnly?generatedService.token:`Object.freeze({...${generatedService.factory}(context,${identity}),Providers:createServiceCatalog<typeof ${generatedService.token}>(context,${generatedService.token},${identity})})`}`;
        if (scope === undefined) result.set(key, member); else serviceMembers.push(member);
      }
      if (scope !== undefined) result.set(scope, `${JSON.stringify(scope)}: Object.freeze({${serviceMembers.join(",\n")}})`);
    }
    return [...result.values()].join(",\n");
  }
  // Provider-only selections still need tokens for their reviewed service targets.
  for(const contract of contracts)members([contract],contract.imported?.authorityId??owner,!!contract.imported);
  const factories = [`function $createSelf(context: ApiBindingContext) { return Object.freeze({${members(contracts.filter(contract => !contract.imported), owner)}}); }`];
  const serviceGroups=[`Self:Object.freeze({${members(contracts.filter(contract=>!contract.imported),owner,false,undefined,undefined,true)}})`];
  const tokens = ["Self"];
  const aliases = new Set(["Self", "SelfModels", "Implementations", "Catalogs", "Errors", "Services"]);
  for (const selection of imports.lock.packageImports.values()) {
    const alias = pascal(selection.localName); if (aliases.has(alias) || aliases.has(alias + "Models")) throw new Error(`rpc-authoring.generated-name-collision: API token '${alias}' collides with a reserved/generated name.`); aliases.add(alias); aliases.add(alias + "Models");
    const artifact = imports.lock.packageArtifacts.get(selection.packageId)!;
    const selected = contracts.filter(contract => contract.imported && artifact.contracts.get(contract.descriptor.contractId)?.authorityKind === "package");
    factories.push(`function $create${alias}(context: ApiBindingContext) { return Object.freeze({${members(selected, selection.packageId, true, artifact.requestedVersionRange, artifact.includePrerelease, false, true)}}); }`);
    tokens.push(alias);
    serviceGroups.push(`${JSON.stringify(alias)}:Object.freeze({${members(selected,selection.packageId,true,artifact.requestedVersionRange,artifact.includePrerelease,true,true)}})`);
  }
  serviceGroups.push(`Contracts:Object.freeze({${contracts.map(contract=>`${JSON.stringify(contractSymbol(contract.descriptor.contractId))}:Object.freeze({${members([contract],contract.imported?.authorityId??owner,!!contract.imported,undefined,undefined,true)}})`).join(",")}})`);
  const modelNamespace = (token: string, selected: readonly LoadedContract[]): void => {
    const names = new Map<string, { identity: string; type: string }>();
    for (const contract of selected) {
      const model = authoringBindingModel(contract.descriptor); const module = modules.get(contract.contractKey!)!;
      const authored = services.find(service => service.key === contract.contractKey && !service.importKey);
      for (const [definition, name] of Object.entries(contract.modelProjection.models).sort(([a],[b])=>a<b?-1:a>b?1:0)) {
        const identity = (contract.imported?.authorityId ?? owner) + "/" + name;
        const previous = names.get(name.toLowerCase());
        if (previous && previous.identity !== identity) throw new Error(`rpc-authoring.generated-name-collision: Distinct model authorities collide at ${token}Models.${name}.`);
        if (!previous) names.set(name.toLowerCase(), { identity, type: `export type ${name} = ${(sourceTypes ? authored?.sourceModels.get(name) : undefined) ?? `${module}.${model.definitionNames.get(definition)!}`};` });
      }
      for (const [definition, type] of model.definitionNames) {
        if (Object.hasOwn(contract.modelProjection.models, definition) || Object.hasOwn(contract.modelProjection.serviceReferences, definition)) continue;
        const schema = contract.descriptor.$defs[definition] as Record<string, unknown>;
        if (schema.type === "object" && schema.properties && Object.keys(schema.properties).length === 0 && schema.additionalProperties === false) continue;
        const name = `${contractSymbol(contract.descriptor.contractId)}_${type}`;
        if (names.has(name.toLowerCase())) throw new Error(`rpc-authoring.generated-name-collision: Generated envelope '${name}' collides with a public model.`);
        names.set(name.toLowerCase(), { identity: contract.descriptor.contractId + "/" + definition, type: `export type ${name} = ${module}.${type};` });
      }
    }
    // Ambient namespaces contain types only: TS imports and JS import(...).X
    // JSDoc share the same declarations, and no models object exists at runtime.
    lines.push(`export declare namespace ${token}Models {\n${[...names].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([, value]) => value.type).join("\n")}\n}`);
  };
  modelNamespace("Self", contracts.filter(contract => !contract.imported));
  for (const selection of imports.lock.packageImports.values()) {
    const artifact = imports.lock.packageArtifacts.get(selection.packageId)!;
    modelNamespace(pascal(selection.localName), contracts.filter(contract => contract.imported && artifact.contracts.get(contract.descriptor.contractId)?.authorityKind === "package"));
  }
  // A wire-compatible local projection change must still retire the old token
  // generation. Bind names/signatures/adapters as well as descriptor/policy tuples.
  const generation = createHash("sha256").update(JSON.stringify({ owner, packageVersion, lock: imports.lock.sha256,
    contracts: contracts.map(contract => [contract.descriptorSha256, contract.modelProjection, contract.methodPolicies, contract.appUse, contract.runtimeUse]),...roleUsesOuter(coalesceRoleUses(services.flatMap(service=>service.roleUses))), factories,serviceDefinitions,serviceGroups })).digest("hex");
  lines.push(...serviceDefinitions,`export const Services=Object.freeze({${serviceGroups.join(",")}});`,...factories,
    ...tokens.map(alias => `export const ${alias}: ApiToken<ReturnType<typeof $create${alias}>> = createApiToken(${JSON.stringify(owner)}, $create${alias}, ${JSON.stringify(generation)},[${[...serviceFactories.values()].map(value=>value.token).join(",")}]);`));
  const implementations: string[] = [];
  for (const [key, contract] of imports.providerSurfaces) {
    const model = authoringBindingModel(contract.descriptor); const module = modules.get(contract.contractKey!)!;
    const methodNames = importedProviderMethodNames(contract.descriptor);
    const methods = model.services.flatMap(service => service.methods.map(method => {
      const name = methodNames.get(`${service.descriptor.serviceId}/${method.descriptor.methodId}`)!;
      const member = `${module}.${service.providerTypeName}[${JSON.stringify(method.methodName)}]`;
      return `${JSON.stringify(name)}: (request: Parameters<${member}>[0], context: ServiceContext) => ReturnType<${member}>${method.descriptor.kind === "unary" ? ` | Awaited<ReturnType<${member}>>` : ""}`;
    }));
    const name = `$implementation${implementations.length}`;
    lines.push(`const ${name}: ServiceContract<{${methods.join(";")}}> = createServiceContract(${JSON.stringify(key)});`);
    implementations.push(`${JSON.stringify(key)}: ${name}`);
  }
  lines.push(`export const Implementations = Object.freeze({${implementations.join(",")}});`);
  lines.push('export { packageApis as Catalogs } from "./catalogs.js";');
  lines.push(`export const Errors = Object.freeze({${contracts.map(contract => {
    const model = authoringBindingModel(contract.descriptor); const module = modules.get(contract.contractKey!)!;
    return `${JSON.stringify(contract.imported ? contract.descriptor.contractId : camel(contract.contractKey!))}: Object.freeze({${model.errors.map(error => {
      const factory=`${module}.${error.factoryName}`;
      return `${JSON.stringify(error.code)}: ${error.detailsReaderName?`Object.freeze(Object.assign((...args:Parameters<typeof ${factory}>):ReturnType<typeof ${factory}>=>${factory}(...args),{details:${module}.${error.detailsReaderName}}))`:factory}`;
    }).join(",")}})`;
  }).join(",")}});`);
  return lines.join("\n") + "\n";
}
function lowerInitial(name: string): string { return name[0]!.toLowerCase() + name.slice(1); }
function contractScope(id: string): string {
  const stem = contractSymbol(id).slice(1);
  return /^[0-9]/u.test(stem) ? `_${stem}` : lowerInitial(stem);
}
function carriesContent(schema: unknown, definitions: Readonly<Record<string, unknown>>, seen = new Set<string>()): boolean {
  if (!schema || typeof schema !== "object") return false;
  if (Array.isArray(schema)) return schema.some(item => carriesContent(item, definitions, seen));
  const value = schema as Record<string, unknown>;
  if (value.logicalType === "content-reference") return true;
  if (typeof value.$ref === "string") {
    if (seen.has(value.$ref)) return false;
    seen.add(value.$ref); return carriesContent(definitions[value.$ref.slice("#/$defs/".length)], definitions, seen);
  }
  return Object.values(value).some(item => carriesContent(item, definitions, seen));
}

export function serviceAdapterSource(modulePath: string, services: readonly SourceService[], contracts: readonly LoadedContract[]): string {
  const lines = ['// <auto-generated />', `import * as source from ${JSON.stringify(modulePath.replace(/\.[jt]s$/u, ".js"))};`, 'import { assertServiceOptions, getApiBindingContext, RpcMarshallingContext, type WorkerContext, type SunderContent, type ServiceReference, type RpcProviderRegistration } from "@sunder/sdk";'];
  // Decoders allocate per-call records/arrays. Remove only the backend's readonly
  // view, not value types, so ordinary mutable Array<T> parameters remain valid.
  lines.push('type $Mutable<T> = T extends Uint8Array | SunderContent | ServiceReference<unknown> ? T : T extends readonly (infer I)[] ? $Mutable<I>[] : T extends object ? {-readonly [K in keyof T]: $Mutable<T[K]>} : T;', 'function $mutable<T>(value:T):$Mutable<T>{return value as $Mutable<T>;}');
  const registrations: string[] = [];
  for (const [index, service] of services.entries()) {
    if (service.declarationOnly) continue;
    const contract = contracts.find(item => item.contractKey === service.key)!; const model = authoringBindingModel(contract.descriptor); const alias = `$service${index}`;
    lines.push(`import * as ${alias} from "./${contract.imported ? "imported/" : "owned/"}${service.key}.js";`);
    lines.push(`const $definition${index} = source[${JSON.stringify(service.exportName)}];`);
    lines.push(`assertServiceOptions($definition${index}, ${JSON.stringify(service.semanticOptions)});`);
    lines.push(`if (!$definition${index}.methods || JSON.stringify(Object.keys($definition${index}.methods).sort()) !== ${JSON.stringify(JSON.stringify(service.methods.map(method => method.name).sort()))}) throw new Error("Service runtime method inventory differs from the checked source.");`);
    const handlers = new Map<string, string>();
    for (const [methodIndex, method] of service.methods.entries()) {
      const stable = `$handler${index}_${methodIndex}`;
      lines.push(`const ${stable} = $definition${index}.methods![${JSON.stringify(method.name)}].bind($definition${index}.methods);`);
      handlers.set(method.name, stable);
    }
    const adapters = model.services.map(group => `{${group.methods.map(method => {
      const authored = service.methods.find(item => item.serviceId === group.descriptor.serviceId && item.wireName === method.descriptor.methodId)!;
      const args = authored.directRequest ? ["$mutable(request)"] : authored.parameters.map(parameter => `$mutable(request[${JSON.stringify(parameter.name)}])`);
      if (authored.control) args.push(authored.control === "signal" ? "context.signal" : "context");
      const invoke = `${handlers.get(authored.name)}(${args.join(", ")})`;
      return `${JSON.stringify(method.methodName)}: (request, context) => ${authored.stream ? invoke : `Promise.resolve(${invoke})${authored.unit ? ".then(() => ({}))" : ""}`}`;
    }).join(",")}}`);
    const completion=Object.fromEntries(model.services.map(group=>[group.descriptor.serviceId,service.methods.filter(method=>method.serviceId===group.descriptor.serviceId&&method.completeOnResponseContentRetirement===true).map(method=>method.wireName)] as const).filter(([,methods])=>methods.length));
    registrations.push(`${alias}.${model.providerRegistrationFactoryName}(${JSON.stringify(service.providerId)}, ${adapters.join(",")}${hasServiceResources(contract)?",invocation=>RpcMarshallingContext.forInvocation(invocation,context?getApiBindingContext(context):undefined),"+JSON.stringify(completion):""})`);
  }
  lines.push(`export function createProviders(context?:Pick<WorkerContext,"api">):readonly RpcProviderRegistration[]{return Object.freeze([${registrations.join(",\n")}]);}`,`export const providers=createProviders();`);
  return lines.join("\n") + "\n";
}
export function serviceWorkerSource(modulePath: string, hasConfigure = false): string {
  return `// <auto-generated />
import { runWorker, bindApiContext, type WorkerOptions, type WorkerContext } from "@sunder/sdk";
import { Self } from "./api.js";
import * as source from ${JSON.stringify(modulePath.replace(/\.[jt]s$/u, ".js"))};
import { createProviders } from "./adapter.js";
void runWorker(context => {
  bindApiContext(context, Self);
  const providers=createProviders(context);
  const configure = ${hasConfigure ? "source.configure" : "undefined"};
  if (configure !== undefined && typeof configure !== "function") throw new Error("Service configure export must be a function.");
  const options = configure === undefined ? {} : (configure as (context: WorkerContext) => Omit<WorkerOptions, "providers">)(context);
  if (Object.hasOwn(options, "providers")) throw new Error("Service provider registration is generated; configure cannot replace it.");
  return { ...options, providers };
}).catch(() => { process.exitCode = 70; });
`;
}
export function serviceTokenTypeName(contractId:string,serviceId:string):string{
  return "$Service_"+contractSymbol(contractId)+"_S"+serviceId.replaceAll("_","_5f").replaceAll(".","_2e").replaceAll("-","_2d");
}
export function serviceReferenceTypes(contract:LoadedContract):Readonly<Record<string,string>>{
  return Object.fromEntries(Object.entries(contract.modelProjection.serviceReferences).map(([key,target])=>[key,
    `import("@sunder/sdk/browser").ServiceReference<import("../api.js").${serviceTokenTypeName(target.contractId,target.serviceId)}>`]));
}
export function hasServiceResources(contract:LoadedContract):boolean{
  return Object.keys(contract.modelProjection.serviceReferences).length>0||contract.naturalContent===true&&carriesContent(contract.descriptor.$defs,contract.descriptor.$defs);
}
