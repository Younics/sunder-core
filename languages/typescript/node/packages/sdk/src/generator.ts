import type { JsonValue, RpcContractDescriptor, RpcErrorDescriptorV1, RpcMethodKind, RpcSchemaReference } from "./types";
import { canonicalizeDescriptor, validateRpcContractDescriptor } from "./descriptor";
import {
  SUNDER_RPC_V1_ABI_DOMAIN_SEPARATOR,
  canonicalRpcAbiProjectionBytes,
  canonicalRpcDescriptorBytes,
} from "./descriptor-v1";
import { sha256Hex } from "./sha256";

export { canonicalizeDescriptor } from "./descriptor";

export interface TypeScriptGeneratorOptions {
  readonly moduleSpecifier?: string;
  readonly coreModuleSpecifier?: string;
  readonly valueModuleSpecifier?: string;
  readonly descriptorSha256?: string;
  readonly abiSha256?: string;
  /** Authoring frontends reject collisions instead of allocating numeric suffixes. */
  readonly strictNames?: boolean;
}

type Schema = Readonly<Record<string, JsonValue>>;
type RecordSchema = Schema & Readonly<{
  type: "object";
  properties: Readonly<Record<string, JsonValue>>;
  additionalProperties: false;
}>;

interface DefinitionModel {
  readonly typeName: string;
  readonly schema: Schema;
  readonly toWireName: string;
  readonly fromWireName: string;
}

interface MethodModel {
  readonly descriptor: GeneratorMethodDescriptor;
  readonly methodName: string;
}

interface ServiceModel {
  readonly descriptor: GeneratorServiceDescriptor;
  readonly providerTypeName: string;
  readonly clientTypeName: string;
  readonly clientPropertyName: string;
  readonly methods: readonly MethodModel[];
}

interface ErrorModel {
  readonly code: string;
  readonly descriptor: RpcErrorDescriptorV1;
  readonly factoryName: string;
  readonly detailsReaderName?: string;
}

interface GeneratorModel {
  readonly jsonObjectTypeName: string;
  readonly definitionNames: ReadonlyMap<string, string>;
  readonly definitions: readonly DefinitionModel[];
  readonly services: readonly ServiceModel[];
  readonly errors: readonly ErrorModel[];
  readonly handlerTypeName: string;
  readonly clientFacadeTypeName: string;
  readonly providerRegistrationFactoryName: string;
  readonly usesContentReference: boolean;
  readonly usesBigInteger: boolean;
  readonly usesBytes: boolean;
  readonly emitsValueConverters: boolean;
  readonly hasServerStreams: boolean;
}

interface GeneratorMethodDescriptor {
  readonly methodId: string;
  readonly kind: RpcMethodKind;
  readonly errors?: readonly string[];
  readonly requestSchema: string | RpcSchemaReference;
  readonly responseSchema?: string | RpcSchemaReference;
  readonly eventSchema?: string | RpcSchemaReference;
}

interface GeneratorServiceDescriptor {
  readonly serviceId: string;
  readonly methods: readonly GeneratorMethodDescriptor[];
}

export function generateTypeScriptBindings(
  descriptor: RpcContractDescriptor,
  options: TypeScriptGeneratorOptions = {},
): string {
  validateRpcContractDescriptor(descriptor);
  validateGeneratorOptions(descriptor, options);
  const moduleSpecifier = options.moduleSpecifier ?? "@sunder/sdk";
  const coreModuleSpecifier = options.coreModuleSpecifier
    ?? (options.moduleSpecifier === undefined ? "@sunder/sdk/core" : moduleSpecifier);
  const valueModuleSpecifier = options.valueModuleSpecifier
    ?? (options.moduleSpecifier === undefined ? "@sunder/sdk/browser" : moduleSpecifier);
  const emitsContractIdentity = options.descriptorSha256 !== undefined;
  const emitsProviderRegistration = emitsContractIdentity;
  const model = buildModel(descriptor, emitsContractIdentity, emitsProviderRegistration, options.strictNames);
  const sdkTypeImports = [
    "RpcContractDescriptor as $RpcContractDescriptor",
    ...(model.usesContentReference ? ["RpcContentReference"] : []),
    ...(emitsContractIdentity ? ["RpcContractIdentity"] : []),
    "RpcInvocationContext",
    "RpcProviderHandler",
    ...(emitsProviderRegistration ? ["RpcProviderRegistration"] : []),
  ].sort(ordinal);
  const sdkValueImports = [...(model.errors.length === 0 ? [] : ["RpcDomainError"]), "validateRpcInstance as $validateRpcInstance"];
  const output: string[] = [
    "// <auto-generated />",
    `import type { ${model.jsonObjectTypeName === "JsonObject" ? "JsonObject" : `JsonObject as ${model.jsonObjectTypeName}`}, JsonValue, RpcCallOptions, RpcInvoker } from ${stringLiteral(coreModuleSpecifier)};`,
    `import type { ${sdkTypeImports.join(", ")} } from ${stringLiteral(moduleSpecifier)};`,
    ...(sdkValueImports.length === 0
      ? []
      : [`import { ${sdkValueImports.join(", ")} } from ${stringLiteral(valueModuleSpecifier)};`]),
    "",
    `export const CONTRACT_ID = ${stringLiteral(descriptor.contractId)} as const;`,
    `export const CONTRACT_VERSION = ${stringLiteral(descriptor.version)} as const;`,
  ];
  if (options.descriptorSha256 !== undefined) {
    output.push(`export const CONTRACT_DESCRIPTOR_SHA256 = ${stringLiteral(options.descriptorSha256)} as const;`);
  }
  if (options.abiSha256 !== undefined) {
    output.push(`export const CONTRACT_ABI_SHA256 = ${stringLiteral(options.abiSha256)} as const;`);
  }
  if (options.descriptorSha256 !== undefined) {
    output.push(
      "export const CONTRACT_IDENTITY = {",
      "  contractId: CONTRACT_ID,",
      "  contractVersion: CONTRACT_VERSION,",
      "  descriptorSha256: CONTRACT_DESCRIPTOR_SHA256,",
      "  abiSha256: CONTRACT_ABI_SHA256,",
      "} as const satisfies RpcContractIdentity;",
    );
  }
  output.push("");
  output.push(`const $rpcDescriptor = JSON.parse(${stringLiteral(canonicalizeDescriptor(descriptor as unknown as JsonValue))}) as $RpcContractDescriptor;`,
    "let $rpcConversionDepth = 0;", "");
  for (const definition of model.definitions) {
    emitDefinition(output, definition, model);
  }
  if (model.emitsValueConverters) emitValueConverters(output, model);
  for (const error of model.errors) emitError(output, error, model);
  for (const service of model.services) {
    emitService(output, service, model);
  }
  emitClientFacade(output, model);
  emitHandler(output, model);
  if (emitsProviderRegistration) {
    emitProviderRegistrationFactory(output, model);
  }
  return `${output.join("\n").replace(/\r\n/gu, "\n")}\n`;
}

function validateGeneratorOptions(
  descriptor: RpcContractDescriptor,
  options: TypeScriptGeneratorOptions,
): void {
  for (const [name, value] of [
    ["descriptorSha256", options.descriptorSha256],
    ["abiSha256", options.abiSha256],
  ] as const) {
    if (value !== undefined && (typeof value !== "string" || !/^[0-9a-f]{64}$/u.test(value))) {
      throw new TypeError(`${name} must be a lowercase 64-character hexadecimal SHA-256 value.`);
    }
  }
  if ((options.descriptorSha256 === undefined) !== (options.abiSha256 === undefined)) {
    throw new TypeError("RPC V1 requires descriptorSha256 and abiSha256 to be provided together.");
  }

  if (options.descriptorSha256 !== undefined
    && options.descriptorSha256 !== sha256Hex(canonicalRpcDescriptorBytes(descriptor))) {
    throw new TypeError("descriptorSha256 does not match the canonical RPC descriptor SHA-256.");
  }
  if (options.abiSha256 !== undefined) {
    const domain = new TextEncoder().encode(SUNDER_RPC_V1_ABI_DOMAIN_SEPARATOR);
    const projection = canonicalRpcAbiProjectionBytes(descriptor);
    const input = new Uint8Array(domain.byteLength + projection.byteLength);
    input.set(domain);
    input.set(projection, domain.byteLength);
    if (options.abiSha256 !== sha256Hex(input)) {
      throw new TypeError("abiSha256 does not match the domain-separated canonical RPC ABI SHA-256.");
    }
  }
}

/** @internal Shared naming model for the source frontend's generated adapters. */
export function authoringBindingModel(descriptor: RpcContractDescriptor) {
  return buildModel(descriptor, true, true, true);
}

function buildModel(
  descriptor: RpcContractDescriptor,
  emitsContractIdentity: boolean,
  emitsProviderRegistration: boolean,
  strictNames = false,
): GeneratorModel {
  const usesContentReference = Object.values(descriptor.$defs).some(schemaUsesContentReference);
  const usesBigInteger = Object.values(descriptor.$defs).some((schema) => schemaUses(schema, (value) => value.format === "big-integer"));
  const usesBytes = Object.values(descriptor.$defs).some((schema) => schemaUses(schema, (value) => value.contentEncoding === "base64"));
  const emitsValueConverters = true;
  const hasDomainErrors = Object.keys(descriptor.errors).length > 0;
  const topLevelNames = new SymbolAllocator(strictNames);
  for (const name of [
    "$base64Alphabet",
    "$base64Value",
    "$fromWireBase64",
    "$fromWireBigInteger",
    "$hasOwn",
    "$invalidUnion",
    "$mapRpcStream",
    "$toWireBase64",
    "$toWireBigInteger",
    "AsyncIterable",
    "CONTRACT_ABI_SHA256",
    "CONTRACT_DESCRIPTOR_SHA256",
    "CONTRACT_ID",
    "CONTRACT_IDENTITY",
    "CONTRACT_VERSION",
    "JsonValue",
    strictNames ? "$JsonObject" : "JsonObject",
    "Promise",
    "Readonly",
    "ReadonlyArray",
    "Record",
    "RpcCallOptions",
    "RpcInvoker",
    "RpcInvocationContext",
    "RpcProviderHandler",
    ...(hasDomainErrors ? ["RpcDomainError"] : []),
    ...(usesContentReference ? ["RpcContentReference"] : []),
    ...(emitsContractIdentity ? ["RpcContractIdentity"] : []),
    ...(emitsProviderRegistration ? ["RpcProviderRegistration"] : []),
    ...(usesBytes ? ["Uint8Array"] : []),
  ]) {
    topLevelNames.reserve(name);
  }

  const definitionNames = new Map<string, string>();
  const pendingDefinitions: Array<Readonly<{ typeName: string; schema: Schema }>> = [];
  for (const name of Object.keys(descriptor.$defs).sort(ordinal)) {
    const schema = descriptor.$defs[name];
    if (schema === undefined) continue;
    const generatedName = topLevelNames.allocate(identifier(name));
    definitionNames.set(name, generatedName);
    pendingDefinitions.push({ typeName: generatedName, schema });
  }
  const definitions = pendingDefinitions.map((definition) => ({
    ...definition,
    toWireName: topLevelNames.allocate(`$toWire${definition.typeName}`),
    fromWireName: topLevelNames.allocate(`$fromWire${definition.typeName}`),
  }));

  const serviceModels: ServiceModel[] = [];
  const clientPropertyNames = new SymbolAllocator(strictNames);
  for (const service of services(descriptor).sort((left, right) => ordinal(left.serviceId, right.serviceId))) {
    const stem = identifier(service.serviceId);
    const methodNames = new SymbolAllocator(strictNames);
    const methodModels = [...service.methods]
      .sort((left, right) => ordinal(left.methodId, right.methodId))
      .map((method) => ({ descriptor: method, methodName: methodNames.allocate(identifier(method.methodId)) }));
    serviceModels.push({
      descriptor: service,
      providerTypeName: topLevelNames.allocate(`I${stem}Provider`),
      clientTypeName: topLevelNames.allocate(`${stem}Client`),
      clientPropertyName: clientPropertyNames.allocate(stem),
      methods: methodModels,
    });
  }

  const contractStem = identifier(descriptor.contractId);
  const rpcStem = contractStem.endsWith("Rpc") ? contractStem : `${contractStem}Rpc`;
  const handlerTypeName = topLevelNames.allocate(`${rpcStem}Handler`);
  const clientFacadeTypeName = topLevelNames.allocate(`${rpcStem}Client`);
  const providerRegistrationFactoryName = topLevelNames.allocate(`create${rpcStem}ProviderRegistration`);
  const errors: ErrorModel[] = Object.entries(descriptor.errors)
    .sort(([left], [right]) => ordinal(left, right))
    .map(([code, declaration]) => {
      const stem = identifier(code);
      const error: ErrorModel = {
        code,
        descriptor: declaration,
        factoryName: topLevelNames.allocate(`create${stem}RpcError`),
      };
      return declaration.detailsSchema === undefined
        ? error
        : { ...error, detailsReaderName: topLevelNames.allocate(`tryGet${stem}RpcErrorDetails`) };
    });
  return {
    jsonObjectTypeName: strictNames ? "$JsonObject" : "JsonObject",
    definitionNames,
    definitions,
    services: serviceModels,
    errors,
    handlerTypeName,
    clientFacadeTypeName,
    providerRegistrationFactoryName,
    usesContentReference,
    usesBigInteger,
    usesBytes,
    emitsValueConverters,
    hasServerStreams: serviceModels.some((service) => service.methods.some((method) => method.descriptor.kind === "server-stream")),
  };
}

function emitError(output: string[], error: ErrorModel, model: GeneratorModel): void {
  const message = defaultErrorMessage(error.descriptor.description);
  if (error.descriptor.detailsSchema === undefined) {
    output.push(
      `export function ${error.factoryName}(message = ${stringLiteral(message)}): RpcDomainError {`,
      `  return new RpcDomainError(${stringLiteral(error.code)}, message);`,
      "}",
      "",
    );
    return;
  }

  const reference = error.descriptor.detailsSchema.$ref;
  const detailsType = referenceType(reference, model);
  const definition = definitionModel(reference, model);
  output.push(
    `export function ${error.factoryName}(details: ${detailsType}, message = ${stringLiteral(message)}): RpcDomainError {`,
    `  return new RpcDomainError(${stringLiteral(error.code)}, message, ${definition.toWireName}(details));`,
    "}",
    "",
    `export function ${error.detailsReaderName!}(error: unknown): ${detailsType} | undefined {`,
    "  if (error === null || typeof error !== \"object\") return undefined;",
    "  const failure = (error as { readonly error?: unknown }).error;",
    "  if (failure === null || typeof failure !== \"object\") return undefined;",
    "  const value = failure as { readonly kind?: unknown; readonly code?: unknown; readonly details?: unknown };",
    `  if (value.kind !== \"domain\" || value.code !== ${stringLiteral(error.code)} || !Object.prototype.hasOwnProperty.call(value, \"details\")) return undefined;`,
    `  return ${definition.fromWireName}(value.details as JsonValue);`,
    "}",
    "",
  );
}

function defaultErrorMessage(description: string | undefined): string {
  const message = description?.replace(/[\u0000-\u001f\u007f]/gu, " ").trim() ?? "";
  if (message.length === 0) return "The provider rejected the request.";
  return message.length <= 512 ? message : message.slice(0, 512);
}

function emitDefinition(
  output: string[],
  definition: DefinitionModel,
  model: GeneratorModel,
): void {
  if (!isRecordSchema(definition.schema)) {
    output.push(`export type ${definition.typeName} = ${typeName(definition.schema, model)};`, "");
    return;
  }

  const properties = definition.schema.properties;
  const required = requiredProperties(definition.schema);
  output.push(`export type ${definition.typeName} = {`);
  for (const propertyName of Object.keys(properties).sort(ordinal)) {
    const propertySchema = properties[propertyName];
    if (!isObject(propertySchema)) continue;
    output.push(`  readonly ${propertyIdentifier(propertyName)}${required.has(propertyName) ? "" : "?"}: ${typeName(propertySchema, model)};`);
  }
  output.push("};", "");
}

function emitValueConverters(output: string[], model: GeneratorModel): void {
  output.push(
    "function $hasOwn(value: object, name: string): boolean {",
    "  return Object.prototype.hasOwnProperty.call(value, name);",
    "}",
    "",
    "function $invalidUnion(): never {",
    "  throw new TypeError(\"RPC value does not contain a recognized union discriminator.\");",
    "}",
    "",
    "function $rpcFloat32(value: unknown): number {",
    "  if (typeof value !== \"number\") throw new TypeError(\"RPC float32 value must be a number.\");",
    "  return Math.fround(value);",
    "}",
    "",
  );
  if (model.usesBigInteger) {
    output.push(
      "function $toWireBigInteger(value: bigint): string {",
      "  if (typeof value !== \"bigint\") throw new TypeError(\"RPC big-integer value must be a bigint.\");",
      "  return value.toString(10);",
      "}",
      "",
      "function $fromWireBigInteger(value: string): bigint {",
      "  if (!/^(?:0|-[1-9][0-9]*|[1-9][0-9]*)$/u.test(value)) throw new TypeError(\"RPC big-integer value is not canonical.\");",
      "  return BigInt(value);",
      "}",
      "",
    );
  }
  if (model.usesBytes) emitBase64Converters(output);
  if (model.hasServerStreams) {
    output.push(
      "async function* $mapRpcStream<TInput, TOutput>(",
      "  source: AsyncIterable<TInput>,",
      "  convert: (value: TInput) => TOutput,",
      "): AsyncIterable<TOutput> {",
      "  for await (const value of source) yield convert(value);",
      "}",
      "",
    );
  }
  for (const definition of model.definitions) {
    const definitionName = [...model.definitionNames].find(([, name]) => name === definition.typeName)![0];
    const reference = stringLiteral(`#/$defs/${definitionName}`);
    output.push(
      `function ${definition.toWireName}(value: ${definition.typeName}, $nested = false): JsonValue {`,
      "  if ($rpcConversionDepth >= 256) throw new TypeError(\"RPC value conversion exceeds the reference-depth budget.\");",
      "  $rpcConversionDepth++;",
      "  try {",
      `    const wire = ${converterExpression(definition.schema, "value", "to-wire", model)};`,
      `    if (!$nested) $validateRpcInstance($rpcDescriptor, ${reference}, wire);`,
      "    return wire;",
      "  } finally { $rpcConversionDepth--; }",
      "}",
      "",
      `function ${definition.fromWireName}(value: JsonValue, $nested = false): ${definition.typeName} {`,
      "  if ($rpcConversionDepth >= 256) throw new TypeError(\"RPC value conversion exceeds the reference-depth budget.\");",
      "  $rpcConversionDepth++;",
      "  try {",
      `    if (!$nested) $validateRpcInstance($rpcDescriptor, ${reference}, value);`,
      `    return ${converterExpression(definition.schema, "value", "from-wire", model)} as ${definition.typeName};`,
      "  } finally { $rpcConversionDepth--; }",
      "}",
      "",
    );
  }
}

function emitBase64Converters(output: string[]): void {
  output.push(
    "const $base64Alphabet = \"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/\";",
    "",
    "function $toWireBase64(value: Uint8Array): string {",
    "  if (!(value instanceof Uint8Array)) throw new TypeError(\"RPC byte value must be a Uint8Array.\");",
    "  let output = \"\";",
    "  for (let index = 0; index < value.byteLength; index += 3) {",
    "    const first = value[index] ?? 0;",
    "    const second = value[index + 1] ?? 0;",
    "    const third = value[index + 2] ?? 0;",
    "    output += $base64Alphabet[first >>> 2];",
    "    output += $base64Alphabet[(first & 3) << 4 | second >>> 4];",
    "    output += index + 1 < value.byteLength ? $base64Alphabet[(second & 15) << 2 | third >>> 6] : \"=\";",
    "    output += index + 2 < value.byteLength ? $base64Alphabet[third & 63] : \"=\";",
    "  }",
    "  return output;",
    "}",
    "",
    "function $fromWireBase64(value: string): Uint8Array {",
    "  if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/u.test(value)) throw new TypeError(\"RPC byte value is not canonical base64.\");",
    "  const padding = value.endsWith(\"==\") ? 2 : value.endsWith(\"=\") ? 1 : 0;",
    "  const output = new Uint8Array(value.length / 4 * 3 - padding);",
    "  let outputIndex = 0;",
    "  for (let index = 0; index < value.length; index += 4) {",
    "    const first = $base64Value(value[index]);",
    "    const second = $base64Value(value[index + 1]);",
    "    const third = value[index + 2] === \"=\" ? 0 : $base64Value(value[index + 2]);",
    "    const fourth = value[index + 3] === \"=\" ? 0 : $base64Value(value[index + 3]);",
    "    if (first < 0 || second < 0 || third < 0 || fourth < 0) throw new TypeError(\"RPC byte value is not canonical base64.\");",
    "    if (outputIndex < output.length) output[outputIndex++] = first << 2 | second >>> 4;",
    "    if (outputIndex < output.length) output[outputIndex++] = (second & 15) << 4 | third >>> 2;",
    "    if (outputIndex < output.length) output[outputIndex++] = (third & 3) << 6 | fourth;",
    "  }",
    "  if (padding === 2 && $base64Value(value[value.length - 3]) % 16 !== 0",
    "    || padding === 1 && $base64Value(value[value.length - 2]) % 4 !== 0) throw new TypeError(\"RPC byte value has nonzero base64 padding bits.\");",
    "  return output;",
    "}",
    "",
    "function $base64Value(value: string | undefined): number {",
    "  if (value === undefined) return -1;",
    "  const code = value.charCodeAt(0);",
    "  if (code >= 65 && code <= 90) return code - 65;",
    "  if (code >= 97 && code <= 122) return code - 97 + 26;",
    "  if (code >= 48 && code <= 57) return code - 48 + 52;",
    "  return value === \"+\" ? 62 : value === \"/\" ? 63 : -1;",
    "}",
    "",
  );
}

type ConverterDirection = "to-wire" | "from-wire";

function converterExpression(
  schema: Schema,
  value: string,
  direction: ConverterDirection,
  model: GeneratorModel,
): string {
  if (typeof schema.$ref === "string") {
    const definition = definitionModel(schema.$ref, model);
    return direction === "to-wire"
      ? `${definition.toWireName}(${value} as ${definition.typeName}, true)`
      : `${definition.fromWireName}(${value} as JsonValue, true)`;
  }
  if (Array.isArray(schema.oneOf)) return unionConverterExpression(schema.oneOf, value, direction, model);
  if (schema.logicalType === "content-reference") return `${value} as unknown as ${direction === "to-wire" ? "JsonValue" : "RpcContentReference"}`;
  if (schema.contentEncoding === "base64") {
    return direction === "to-wire"
      ? `$toWireBase64(${value} as Uint8Array)`
      : `$fromWireBase64(${value} as string)`;
  }
  if (schema.format === "big-integer") {
    return direction === "to-wire"
      ? `$toWireBigInteger(${value} as bigint)`
      : `$fromWireBigInteger(${value} as string)`;
  }
  if (schema.type === "number" && schema.format === "float32") return `$rpcFloat32(${value})`;
  if (Object.keys(schema).every((name) => name === "title" || name === "description")) return `${value} as JsonValue`;

  switch (schema.type) {
    case "array": {
      if (!isObject(schema.items)) return `${value} as JsonValue`;
      const converted = converterExpression(schema.items, "$item", direction, model);
      return `(${value} as readonly unknown[]).map(($item) => ${converted}) as ${direction === "to-wire" ? "JsonValue" : "unknown"}`;
    }
    case "object":
      if (isDynamicObjectSchema(schema)) return `${value} as ${direction === "to-wire" ? model.jsonObjectTypeName : "unknown"}`;
      if (isRecordSchema(schema)) return recordConverterExpression(schema, value, direction, model);
      if (isObject(schema.additionalProperties)) {
        const itemValue = `(${value} as Readonly<Record<string, unknown>>)[$key]`;
        const converted = converterExpression(schema.additionalProperties, itemValue, direction, model);
        return `(Object.fromEntries(Object.keys(${value} as object).sort().map(($key) => [$key, ${converted}])) as ${direction === "to-wire" ? model.jsonObjectTypeName : "unknown"})`;
      }
      return `${value} as ${direction === "to-wire" ? "JsonValue" : "unknown"}`;
    default:
      return `${value} as ${direction === "to-wire" ? "JsonValue" : "unknown"}`;
  }
}

function recordConverterExpression(
  schema: RecordSchema,
  value: string,
  direction: ConverterDirection,
  model: GeneratorModel,
): string {
  const required = requiredProperties(schema);
  const entries: string[] = [];
  for (const propertyName of Object.keys(schema.properties).sort(ordinal)) {
    const propertySchema = schema.properties[propertyName];
    if (!isObject(propertySchema)) continue;
    const property = stringLiteral(propertyName);
    const propertyValue = `(${value} as Readonly<Record<string, unknown>>)[${property}]`;
    const converted = converterExpression(propertySchema, propertyValue, direction, model);
    const entry = `[${property}, ${converted}]`;
    entries.push(required.has(propertyName)
      ? entry
      : `...($hasOwn(${value} as object, ${property}) ? [${entry}] : [])`);
  }
  return `(Object.fromEntries([${entries.join(", ")}]) as ${direction === "to-wire" ? model.jsonObjectTypeName : "unknown"})`;
}

function unionConverterExpression(
  values: readonly JsonValue[],
  value: string,
  direction: ConverterDirection,
  model: GeneratorModel,
): string {
  const variants = values.filter(isObject);
  const nullVariant = variants.find((variant) => resolveGeneratorSchema(variant, model).type === "null");
  if (variants.length === 2 && nullVariant !== undefined) {
    const nonNull = variants.find((variant) => variant !== nullVariant);
    return nonNull === undefined
      ? "$invalidUnion()"
      : `(${value} === null ? null : ${converterExpression(nonNull, value, direction, model)})`;
  }
  const resolved = variants.map((variant) => resolveGeneratorSchema(variant, model));
  const discriminator = generatorDiscriminator(resolved);
  let expression = "$invalidUnion()";
  for (let index = variants.length - 1; index >= 0; index--) {
    const variant = variants[index];
    const resolvedVariant = resolved[index];
    if (variant === undefined || resolvedVariant === undefined) continue;
    const property = isObject(resolvedVariant.properties) ? resolvedVariant.properties[discriminator] : undefined;
    if (!isObject(property) || typeof property.const !== "string") continue;
    expression = `(${value} as unknown as ${model.jsonObjectTypeName})[${stringLiteral(discriminator)}] === ${stringLiteral(property.const)} ? ${converterExpression(variant, value, direction, model)} : ${expression}`;
  }
  return `(${expression})`;
}

function definitionModel(reference: string, model: GeneratorModel): DefinitionModel {
  const name = reference.startsWith("#/$defs/") ? reference.slice("#/$defs/".length) : "";
  const typeName = model.definitionNames.get(name);
  const definition = model.definitions.find((candidate) => candidate.typeName === typeName);
  if (definition === undefined) throw new TypeError(`RPC schema reference '${reference}' is missing from the generator model.`);
  return definition;
}

function resolveGeneratorSchema(schema: Schema, model: GeneratorModel): Schema {
  const seen = new Set<string>();
  while (typeof schema.$ref === "string") {
    if (seen.has(schema.$ref)) throw new TypeError("RPC schema contains a non-productive reference cycle.");
    seen.add(schema.$ref);
    schema = definitionModel(schema.$ref, model).schema;
  }
  return schema;
}

function generatorDiscriminator(variants: readonly Schema[]): string {
  let candidates: Set<string> | undefined;
  for (const schema of variants) {
    if (!isObject(schema.properties)) return "";
    const properties = schema.properties;
    const required = new Set(Array.isArray(schema.required) ? schema.required.filter((value): value is string => typeof value === "string") : []);
    const current = new Set(Object.keys(properties).filter((name) => {
      const property = properties[name];
      return required.has(name) && isObject(property) && typeof property.const === "string";
    }));
    candidates = candidates === undefined ? current : new Set([...candidates].filter((name) => current.has(name)));
  }
  const discriminator = [...(candidates ?? [])].find((name) => {
    const tags = variants.map((variant) => {
      const property = isObject(variant.properties) ? variant.properties[name] : undefined;
      return isObject(property) ? property.const : undefined;
    });
    return tags.every((tag) => typeof tag === "string") && new Set(tags).size === variants.length;
  });
  if (discriminator === undefined) throw new TypeError("RPC tagged union has no generator discriminator.");
  return discriminator;
}

function emitService(
  output: string[],
  service: ServiceModel,
  model: GeneratorModel,
): void {
  output.push(`export interface ${service.providerTypeName} {`);
  for (const method of service.methods) {
    const request = referenceType(schemaReference(method.descriptor.requestSchema), model);
    const result = referenceType(schemaReference(method.descriptor.kind === "unary" ? method.descriptor.responseSchema : method.descriptor.eventSchema), model);
    const returnType = method.descriptor.kind === "unary" ? `Promise<${result}>` : `AsyncIterable<${result}>`;
    output.push(`  ${method.methodName}(request: ${request}, context: RpcInvocationContext): ${returnType};`);
  }
  output.push("}", "", `export class ${service.clientTypeName}<TTarget = string> {`, "  readonly #invoker: RpcInvoker<TTarget>;", "  readonly #target: TTarget;", "", "  public constructor(invoker: RpcInvoker<TTarget>, target: TTarget) {", "    this.#invoker = invoker;", "    this.#target = target;", "  }", "");
  for (const method of service.methods) {
    const requestReference = schemaReference(method.descriptor.requestSchema);
    const resultReference = schemaReference(method.descriptor.kind === "unary" ? method.descriptor.responseSchema : method.descriptor.eventSchema);
    const request = referenceType(requestReference, model);
    const result = referenceType(resultReference, model);
    const returnType = method.descriptor.kind === "unary" ? `Promise<${result}>` : `AsyncIterable<${result}>`;
    const operation = method.descriptor.kind === "unary" ? "invoke" : "subscribe";
    if (!model.emitsValueConverters) {
      output.push(
        `  public ${method.methodName}(request: ${request}, options?: RpcCallOptions): ${returnType} {`,
        `    return this.#invoker.${operation}<${request}, ${result}>(this.#target, ${stringLiteral(service.descriptor.serviceId)}, ${stringLiteral(method.descriptor.methodId)}, request, options);`,
        "  }",
        "",
      );
      continue;
    }
    const requestConverter = definitionModel(requestReference, model).toWireName;
    const resultConverter = definitionModel(resultReference, model).fromWireName;
    const invocation = `this.#invoker.${operation}<JsonValue, JsonValue>(this.#target, ${stringLiteral(service.descriptor.serviceId)}, ${stringLiteral(method.descriptor.methodId)}, ${requestConverter}(request), options)`;
    output.push(
      `  public ${method.methodName}(request: ${request}, options?: RpcCallOptions): ${returnType} {`,
      method.descriptor.kind === "unary"
        ? `    return ${invocation}.then(${resultConverter});`
        : `    return $mapRpcStream(${invocation}, ${resultConverter});`,
      "  }",
      "",
    );
  }
  output.push("}", "");
}

function emitClientFacade(output: string[], model: GeneratorModel): void {
  output.push(`export class ${model.clientFacadeTypeName}<TTarget = string> {`);
  for (const service of model.services) {
    output.push(`  public readonly ${service.clientPropertyName}: ${service.clientTypeName}<TTarget>;`);
  }
  output.push("", "  public constructor(invoker: RpcInvoker<TTarget>, target: TTarget) {");
  for (const service of model.services) {
    output.push(`    this.${service.clientPropertyName} = new ${service.clientTypeName}(invoker, target);`);
  }
  output.push("  }", "}", "");
}

function emitHandler(output: string[], model: GeneratorModel): void {
  output.push(`export class ${model.handlerTypeName} implements RpcProviderHandler {`);
  for (const [index, service] of model.services.entries()) {
    output.push(`  readonly #service${index + 1}: ${service.providerTypeName};`);
  }
  output.push("");
  output.push(`  public constructor(${model.services.map((service, index) => `service${index + 1}: ${service.providerTypeName}`).join(", ")}) {`);
  for (const [index] of model.services.entries()) {
    output.push(`    this.#service${index + 1} = service${index + 1};`);
  }
  output.push("  }", "", "  public invokeUnary(", "    context: RpcInvocationContext,", "    serviceId: string,", "    methodId: string,", "    request: JsonValue,", "  ): Promise<JsonValue> | JsonValue {");
  for (let serviceIndex = 0; serviceIndex < model.services.length; serviceIndex++) {
    const service = model.services[serviceIndex];
    if (service === undefined) continue;
    for (const method of service.methods) {
      if (method.descriptor.kind !== "unary") continue;
      const request = referenceType(schemaReference(method.descriptor.requestSchema), model);
      const requestReference = schemaReference(method.descriptor.requestSchema);
      const resultReference = schemaReference(method.descriptor.responseSchema);
      output.push(`    if (serviceId === ${stringLiteral(service.descriptor.serviceId)} && methodId === ${stringLiteral(method.descriptor.methodId)}) {`);
      if (model.emitsValueConverters) {
        output.push(`      return this.#service${serviceIndex + 1}.${method.methodName}(${definitionModel(requestReference, model).fromWireName}(request), context).then(${definitionModel(resultReference, model).toWireName});`);
      } else {
        output.push(`      return this.#service${serviceIndex + 1}.${method.methodName}(request as ${request}, context);`);
      }
      output.push("    }");
    }
  }
  output.push(
    "    throw new Error(`Unknown unary RPC method '${serviceId}/${methodId}' for contract '${CONTRACT_ID}'.`);",
    "  }",
    "",
    "  public invokeServerStream(",
    "    context: RpcInvocationContext,",
    "    serviceId: string,",
    "    methodId: string,",
    "    request: JsonValue,",
    "  ): AsyncIterable<JsonValue> {",
  );
  for (let serviceIndex = 0; serviceIndex < model.services.length; serviceIndex++) {
    const service = model.services[serviceIndex];
    if (service === undefined) continue;
    for (const method of service.methods) {
      if (method.descriptor.kind !== "server-stream") continue;
      const request = referenceType(schemaReference(method.descriptor.requestSchema), model);
      const requestReference = schemaReference(method.descriptor.requestSchema);
      const resultReference = schemaReference(method.descriptor.eventSchema);
      output.push(`    if (serviceId === ${stringLiteral(service.descriptor.serviceId)} && methodId === ${stringLiteral(method.descriptor.methodId)}) {`);
      if (model.emitsValueConverters) {
        output.push(`      return $mapRpcStream(this.#service${serviceIndex + 1}.${method.methodName}(${definitionModel(requestReference, model).fromWireName}(request), context), ${definitionModel(resultReference, model).toWireName});`);
      } else {
        output.push(`      return this.#service${serviceIndex + 1}.${method.methodName}(request as ${request}, context);`);
      }
      output.push("    }");
    }
  }
  output.push(
    "    throw new Error(`Unknown server-stream RPC method '${serviceId}/${methodId}' for contract '${CONTRACT_ID}'.`);",
    "  }",
    "}",
    "",
  );
}

function emitProviderRegistrationFactory(
  output: string[],
  model: GeneratorModel,
): void {
  output.push(
    `export function ${model.providerRegistrationFactoryName}(`,
    "  providerId: string,",
  );
  for (const [index, service] of model.services.entries()) {
    output.push(`  service${index + 1}: ${service.providerTypeName},`);
  }
  output.push(
    "): RpcProviderRegistration {",
    "  return {",
    "    ...CONTRACT_IDENTITY,",
    "    providerId,",
    "    declaredErrors: {",
  );
  for (const service of model.services) {
    output.push(`      ${stringLiteral(service.descriptor.serviceId)}: {`);
    for (const method of service.methods) {
      output.push(`        ${stringLiteral(method.descriptor.methodId)}: ${JSON.stringify(method.descriptor.errors ?? [])},`);
    }
    output.push("      },");
  }
  output.push(
    "    },",
    `    handler: new ${model.handlerTypeName}(${model.services.map((_service, index) => `service${index + 1}`).join(", ")}),`,
    "  };",
    "}",
    "",
  );
}

function typeName(
  schema: Schema,
  model: GeneratorModel,
): string {
  if (typeof schema.$ref === "string") return referenceType(schema.$ref, model);
  if (schema.logicalType === "content-reference") return "RpcContentReference";
  if (schema.contentEncoding === "base64") return "Uint8Array";
  if (schema.format === "big-integer") return "bigint";
  if (schema.type === "string" && typeof schema.format === "string") return "string";
  const literal = literalSchemaType(schema);
  if (literal !== undefined) return literal;
  if (Array.isArray(schema.oneOf)) {
    const variants: string[] = [];
    for (const variant of schema.oneOf) {
      if (!isObject(variant)) return "JsonValue";
      variants.push(typeName(variant, model));
    }
    return unionType(variants);
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return isObject(schema.items) ? `ReadonlyArray<${typeName(schema.items, model)}>` : "ReadonlyArray<JsonValue>";
    case "object":
      if (isDynamicObjectSchema(schema)) return model.jsonObjectTypeName;
      if (isObject(schema.additionalProperties)) {
        return `Readonly<Record<string, ${typeName(schema.additionalProperties, model)}>>`;
      }
      return isRecordSchema(schema) ? inlineRecordType(schema, model) : "JsonValue";
    default:
      return "JsonValue";
  }
}

function referenceType(
  reference: string,
  model: GeneratorModel,
): string {
  const prefix = "#/$defs/";
  if (!reference.startsWith(prefix)) return "JsonValue";
  return model.definitionNames.get(reference.slice(prefix.length)) ?? "JsonValue";
}

function literalSchemaType(schema: Schema): string | undefined {
  // Float32 codecs round binary64 JS numbers, so descriptor spellings such as
  // 0.1 are not the decoded JS literal. Integer and float64 literals are exact.
  if (schema.type === "number" && schema.format === "float32") return undefined;
  if (hasOwn(schema, "const")) return literalType(schema.const ?? null);
  if (Array.isArray(schema.enum)) return unionType(schema.enum.map((value) => literalType(value)));
  return undefined;
}

function literalType(value: JsonValue): string {
  if (value === null) return "null";
  if (typeof value === "string") return stringLiteral(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return "JsonValue";
}

function unionType(types: readonly string[]): string {
  const unique = [...new Set(types)];
  if (unique.length === 0 || unique.includes("JsonValue")) return "JsonValue";
  return unique.join(" | ");
}

function inlineRecordType(schema: RecordSchema, model: GeneratorModel): string {
  const required = requiredProperties(schema);
  const properties: string[] = [];
  for (const propertyName of Object.keys(schema.properties).sort(ordinal)) {
    const propertySchema = schema.properties[propertyName];
    if (!isObject(propertySchema)) continue;
    properties.push(`readonly ${propertyIdentifier(propertyName)}${required.has(propertyName) ? "" : "?"}: ${typeName(propertySchema, model)};`);
  }
  return properties.length === 0 ? "{}" : `{ ${properties.join(" ")} }`;
}

function requiredProperties(schema: Schema): ReadonlySet<string> {
  return new Set(Array.isArray(schema.required)
    ? schema.required.filter((value): value is string => typeof value === "string")
    : []);
}

function isRecordSchema(schema: Schema): schema is RecordSchema {
  return schema.type === "object"
    && schema.additionalProperties === false
    && isObject(schema.properties);
}

function schemaReference(value: string | RpcSchemaReference | undefined): string {
  if (typeof value === "string") return value;
  if (value !== undefined && typeof value.$ref === "string") return value.$ref;
  throw new TypeError("RPC method schema must be a local definition reference.");
}

function services(descriptor: RpcContractDescriptor): GeneratorServiceDescriptor[] {
  return Object.entries(descriptor.services).map(([serviceId, service]) => ({
    serviceId,
    methods: Object.entries(service.methods).map(([methodId, method]) => ({ ...method, methodId })),
  }));
}

function identifier(value: string): string {
  let output = "";
  let capitalize = true;
  for (const character of value) {
    if (!/[A-Za-z0-9]/u.test(character)) {
      capitalize = true;
      continue;
    }
    output += capitalize ? character.toUpperCase() : character;
    capitalize = false;
  }
  if (output.length === 0) output = "Value";
  if (/^[0-9]/u.test(output)) output = `_${output}`;
  return output;
}

function propertyIdentifier(value: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(value) ? value : stringLiteral(value);
}

function stringLiteral(value: string): string {
  return JSON.stringify(value)
    .replace(/\u2028/gu, "\\u2028")
    .replace(/\u2029/gu, "\\u2029");
}

function hasOwn(object: Schema, name: string): boolean {
  return Object.prototype.hasOwnProperty.call(object, name);
}

function isObject(value: unknown): value is Readonly<Record<string, JsonValue>> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function schemaUsesContentReference(value: JsonValue): boolean {
  if (Array.isArray(value)) return value.some(schemaUsesContentReference);
  if (!isObject(value)) return false;
  if (value.logicalType === "content-reference") return true;
  return Object.values(value).some(schemaUsesContentReference);
}

function schemaUses(value: JsonValue, predicate: (schema: Schema) => boolean): boolean {
  if (Array.isArray(value)) return value.some((item) => schemaUses(item, predicate));
  if (!isObject(value)) return false;
  if (predicate(value)) return true;
  return Object.values(value).some((item) => schemaUses(item, predicate));
}

function isDynamicObjectSchema(schema: Schema): boolean {
  return schema.type === "object"
    && Object.keys(schema).every((name) => name === "type" || name === "maxProperties" || name === "title" || name === "description");
}

class SymbolAllocator {
  readonly #used = new Set<string>();

  public constructor(private readonly strict = false) {}

  public reserve(value: string): void {
    this.#used.add(value);
  }

  public allocate(preferred: string): string {
    if (this.strict && [...this.#used].some((name) => name.toLowerCase() === preferred.toLowerCase())) {
      throw new Error(`rpc-authoring.generated-name-collision: '${preferred}' collides with a generated binding symbol.`);
    }
    if (!this.#used.has(preferred)) {
      this.#used.add(preferred);
      return preferred;
    }
    for (let suffix = 2; ; suffix++) {
      const candidate = `${preferred}${suffix}`;
      if (this.#used.has(candidate)) continue;
      this.#used.add(candidate);
      return candidate;
    }
  }
}

function ordinal(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}
