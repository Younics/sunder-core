import type { JsonValue, RpcContractDescriptor, RpcMethodKind, RpcSchemaReference } from "./types";
import { canonicalizeDescriptor, validateRpcContractDescriptor } from "./descriptor";
import {
  SUNDER_RPC_V2_ABI_DOMAIN_SEPARATOR,
  canonicalRpcAbiProjectionBytes,
  canonicalRpcDescriptorBytes,
} from "./descriptor-v2";
import { sha256Hex } from "./sha256";

export { canonicalizeDescriptor } from "./descriptor";

export interface TypeScriptGeneratorOptions {
  readonly moduleSpecifier?: string;
  readonly coreModuleSpecifier?: string;
  readonly descriptorSha256?: string;
  readonly abiSha256?: string;
}

type Schema = Readonly<Record<string, JsonValue>>;
type RecordSchema = Schema & Readonly<{
  type: "object";
  properties: Readonly<Record<string, JsonValue>>;
  additionalProperties: false;
}>;

interface DefinitionModel {
  readonly typeName: string;
  readonly schema: Schema;
}

interface MethodModel {
  readonly descriptor: GeneratorMethodDescriptor;
  readonly methodName: string;
}

interface ServiceModel {
  readonly descriptor: GeneratorServiceDescriptor;
  readonly providerTypeName: string;
  readonly clientTypeName: string;
  readonly clientPropertyName: string;
  readonly methods: readonly MethodModel[];
}

interface GeneratorModel {
  readonly definitionNames: ReadonlyMap<string, string>;
  readonly definitions: readonly DefinitionModel[];
  readonly services: readonly ServiceModel[];
  readonly handlerTypeName: string;
  readonly clientFacadeTypeName: string;
  readonly providerRegistrationFactoryName: string;
  readonly usesContentReference: boolean;
}

interface GeneratorMethodDescriptor {
  readonly methodId: string;
  readonly kind: RpcMethodKind;
  readonly errors?: readonly string[];
  readonly requestSchema: string | RpcSchemaReference;
  readonly responseSchema?: string | RpcSchemaReference;
  readonly eventSchema?: string | RpcSchemaReference;
}

interface GeneratorServiceDescriptor {
  readonly serviceId: string;
  readonly methods: readonly GeneratorMethodDescriptor[];
}

export function generateTypeScriptBindings(
  descriptor: RpcContractDescriptor,
  options: TypeScriptGeneratorOptions = {},
): string {
  validateRpcContractDescriptor(descriptor);
  validateGeneratorOptions(descriptor, options);
  const moduleSpecifier = options.moduleSpecifier ?? "@sunder/sdk";
  const coreModuleSpecifier = options.coreModuleSpecifier
    ?? (options.moduleSpecifier === undefined ? "@sunder/sdk/core" : moduleSpecifier);
  const emitsContractIdentity = options.descriptorSha256 !== undefined;
  const emitsProviderRegistration = descriptor.descriptorVersion === 2 && emitsContractIdentity;
  const contractIdentityType = descriptor.descriptorVersion === 1 ? "RpcContractIdentity" : "RpcContractIdentityV2";
  const model = buildModel(descriptor, emitsContractIdentity, emitsProviderRegistration);
  const sdkTypeImports = [
    ...(model.usesContentReference ? ["RpcContentReference"] : []),
    ...(emitsContractIdentity ? [contractIdentityType] : []),
    "RpcInvocationContext",
    "RpcProviderHandler",
    ...(emitsProviderRegistration ? ["RpcProviderRegistration"] : []),
  ].sort(ordinal);
  const output: string[] = [
    "// <auto-generated />",
    `import type { JsonValue, RpcCallOptions, RpcInvoker } from ${stringLiteral(coreModuleSpecifier)};`,
    `import type { ${sdkTypeImports.join(", ")} } from ${stringLiteral(moduleSpecifier)};`,
    "",
    `export const CONTRACT_ID = ${stringLiteral(descriptor.contractId)} as const;`,
    `export const CONTRACT_VERSION = ${stringLiteral(descriptor.version)} as const;`,
  ];
  if (options.descriptorSha256 !== undefined) {
    output.push(`export const CONTRACT_DESCRIPTOR_SHA256 = ${stringLiteral(options.descriptorSha256)} as const;`);
  }
  if (options.abiSha256 !== undefined) {
    output.push(`export const CONTRACT_ABI_SHA256 = ${stringLiteral(options.abiSha256)} as const;`);
  }
  if (options.descriptorSha256 !== undefined) {
    if (descriptor.descriptorVersion === 1) {
      output.push(
        "export const CONTRACT_IDENTITY = {",
        "  contractId: CONTRACT_ID,",
        "  contractVersion: CONTRACT_VERSION,",
        "  contractSha256: CONTRACT_DESCRIPTOR_SHA256,",
        "} as const satisfies RpcContractIdentity;",
      );
    } else {
      output.push(
        "export const CONTRACT_IDENTITY = {",
        "  contractId: CONTRACT_ID,",
        "  contractVersion: CONTRACT_VERSION,",
        "  descriptorSha256: CONTRACT_DESCRIPTOR_SHA256,",
        "  abiSha256: CONTRACT_ABI_SHA256,",
        "} as const satisfies RpcContractIdentityV2;",
      );
    }
  }
  output.push("");
  for (const definition of model.definitions) {
    emitDefinition(output, definition, model);
  }
  for (const service of model.services) {
    emitService(output, service, model);
  }
  emitClientFacade(output, model);
  emitHandler(output, model);
  if (emitsProviderRegistration) {
    emitProviderRegistrationFactory(output, model);
  }
  return `${output.join("\n").replace(/\r\n/gu, "\n")}\n`;
}

function validateGeneratorOptions(
  descriptor: RpcContractDescriptor,
  options: TypeScriptGeneratorOptions,
): void {
  for (const [name, value] of [
    ["descriptorSha256", options.descriptorSha256],
    ["abiSha256", options.abiSha256],
  ] as const) {
    if (value !== undefined && (typeof value !== "string" || !/^[0-9a-f]{64}$/u.test(value))) {
      throw new TypeError(`${name} must be a lowercase 64-character hexadecimal SHA-256 value.`);
    }
  }
  if (descriptor.descriptorVersion === 1) {
    if (options.abiSha256 !== undefined) {
      throw new TypeError("abiSha256 is not valid for descriptor version 1.");
    }
  } else if ((options.descriptorSha256 === undefined) !== (options.abiSha256 === undefined)) {
    throw new TypeError("Descriptor version 2 requires descriptorSha256 and abiSha256 to be provided together.");
  }

  if (options.descriptorSha256 !== undefined
    && options.descriptorSha256 !== sha256Hex(canonicalRpcDescriptorBytes(descriptor))) {
    throw new TypeError("descriptorSha256 does not match the canonical RPC descriptor SHA-256.");
  }
  if (descriptor.descriptorVersion === 2 && options.abiSha256 !== undefined) {
    const domain = new TextEncoder().encode(SUNDER_RPC_V2_ABI_DOMAIN_SEPARATOR);
    const projection = canonicalRpcAbiProjectionBytes(descriptor);
    const input = new Uint8Array(domain.byteLength + projection.byteLength);
    input.set(domain);
    input.set(projection, domain.byteLength);
    if (options.abiSha256 !== sha256Hex(input)) {
      throw new TypeError("abiSha256 does not match the domain-separated canonical RPC ABI SHA-256.");
    }
  }
}

function buildModel(
  descriptor: RpcContractDescriptor,
  emitsContractIdentity: boolean,
  emitsProviderRegistration: boolean,
): GeneratorModel {
  const usesContentReference = Object.values(descriptor.$defs).some(schemaUsesContentReference);
  const topLevelNames = new SymbolAllocator();
  for (const name of [
    "AsyncIterable",
    "CONTRACT_ABI_SHA256",
    "CONTRACT_DESCRIPTOR_SHA256",
    "CONTRACT_ID",
    "CONTRACT_IDENTITY",
    "CONTRACT_VERSION",
    "JsonValue",
    "Promise",
    "Readonly",
    "ReadonlyArray",
    "Record",
    "RpcCallOptions",
    "RpcInvoker",
    "RpcInvocationContext",
    "RpcProviderHandler",
    ...(usesContentReference ? ["RpcContentReference"] : []),
    ...(emitsContractIdentity
      ? [descriptor.descriptorVersion === 1 ? "RpcContractIdentity" : "RpcContractIdentityV2"]
      : []),
    ...(emitsProviderRegistration ? ["RpcProviderRegistration"] : []),
  ]) {
    topLevelNames.reserve(name);
  }

  const definitionNames = new Map<string, string>();
  const definitions: DefinitionModel[] = [];
  for (const name of Object.keys(descriptor.$defs).sort(ordinal)) {
    const schema = descriptor.$defs[name];
    if (schema === undefined) continue;
    const generatedName = topLevelNames.allocate(identifier(name));
    definitionNames.set(name, generatedName);
    definitions.push({ typeName: generatedName, schema });
  }

  const serviceModels: ServiceModel[] = [];
  const clientPropertyNames = new SymbolAllocator();
  for (const service of services(descriptor).sort((left, right) => ordinal(left.serviceId, right.serviceId))) {
    const stem = identifier(service.serviceId);
    const methodNames = new SymbolAllocator();
    const methodModels = [...service.methods]
      .sort((left, right) => ordinal(left.methodId, right.methodId))
      .map((method) => ({ descriptor: method, methodName: methodNames.allocate(identifier(method.methodId)) }));
    serviceModels.push({
      descriptor: service,
      providerTypeName: topLevelNames.allocate(`I${stem}Provider`),
      clientTypeName: topLevelNames.allocate(`${stem}Client`),
      clientPropertyName: clientPropertyNames.allocate(stem),
      methods: methodModels,
    });
  }

  const contractStem = identifier(descriptor.contractId);
  const rpcStem = contractStem.endsWith("Rpc") ? contractStem : `${contractStem}Rpc`;
  const handlerTypeName = topLevelNames.allocate(`${rpcStem}Handler`);
  const clientFacadeTypeName = topLevelNames.allocate(`${rpcStem}Client`);
  const providerRegistrationFactoryName = topLevelNames.allocate(`create${rpcStem}ProviderRegistration`);
  return {
    definitionNames,
    definitions,
    services: serviceModels,
    handlerTypeName,
    clientFacadeTypeName,
    providerRegistrationFactoryName,
    usesContentReference,
  };
}

function emitDefinition(
  output: string[],
  definition: DefinitionModel,
  model: GeneratorModel,
): void {
  if (!isRecordSchema(definition.schema)) {
    output.push(`export type ${definition.typeName} = ${typeName(definition.schema, model)};`, "");
    return;
  }

  const properties = definition.schema.properties;
  const required = requiredProperties(definition.schema);
  output.push(`export type ${definition.typeName} = {`);
  for (const propertyName of Object.keys(properties).sort(ordinal)) {
    const propertySchema = properties[propertyName];
    if (!isObject(propertySchema)) continue;
    output.push(`  readonly ${propertyIdentifier(propertyName)}${required.has(propertyName) ? "" : "?"}: ${typeName(propertySchema, model)};`);
  }
  output.push("};", "");
}

function emitService(
  output: string[],
  service: ServiceModel,
  model: GeneratorModel,
): void {
  output.push(`export interface ${service.providerTypeName} {`);
  for (const method of service.methods) {
    const request = referenceType(schemaReference(method.descriptor.requestSchema), model);
    const result = referenceType(schemaReference(method.descriptor.kind === "unary" ? method.descriptor.responseSchema : method.descriptor.eventSchema), model);
    const returnType = method.descriptor.kind === "unary" ? `Promise<${result}>` : `AsyncIterable<${result}>`;
    output.push(`  ${method.methodName}(request: ${request}, context: RpcInvocationContext): ${returnType};`);
  }
  output.push("}", "", `export class ${service.clientTypeName}<TTarget = string> {`, "  readonly #invoker: RpcInvoker<TTarget>;", "  readonly #target: TTarget;", "", "  public constructor(invoker: RpcInvoker<TTarget>, target: TTarget) {", "    this.#invoker = invoker;", "    this.#target = target;", "  }", "");
  for (const method of service.methods) {
    const request = referenceType(schemaReference(method.descriptor.requestSchema), model);
    const result = referenceType(schemaReference(method.descriptor.kind === "unary" ? method.descriptor.responseSchema : method.descriptor.eventSchema), model);
    const returnType = method.descriptor.kind === "unary" ? `Promise<${result}>` : `AsyncIterable<${result}>`;
    const operation = method.descriptor.kind === "unary" ? "invoke" : "subscribe";
    output.push(
      `  public ${method.methodName}(request: ${request}, options?: RpcCallOptions): ${returnType} {`,
      `    return this.#invoker.${operation}<${request}, ${result}>(this.#target, ${stringLiteral(service.descriptor.serviceId)}, ${stringLiteral(method.descriptor.methodId)}, request, options);`,
      "  }",
      "",
    );
  }
  output.push("}", "");
}

function emitClientFacade(output: string[], model: GeneratorModel): void {
  output.push(`export class ${model.clientFacadeTypeName}<TTarget = string> {`);
  for (const service of model.services) {
    output.push(`  public readonly ${service.clientPropertyName}: ${service.clientTypeName}<TTarget>;`);
  }
  output.push("", "  public constructor(invoker: RpcInvoker<TTarget>, target: TTarget) {");
  for (const service of model.services) {
    output.push(`    this.${service.clientPropertyName} = new ${service.clientTypeName}(invoker, target);`);
  }
  output.push("  }", "}", "");
}

function emitHandler(output: string[], model: GeneratorModel): void {
  output.push(`export class ${model.handlerTypeName} implements RpcProviderHandler {`);
  for (const [index, service] of model.services.entries()) {
    output.push(`  readonly #service${index + 1}: ${service.providerTypeName};`);
  }
  output.push("");
  output.push(`  public constructor(${model.services.map((service, index) => `service${index + 1}: ${service.providerTypeName}`).join(", ")}) {`);
  for (const [index] of model.services.entries()) {
    output.push(`    this.#service${index + 1} = service${index + 1};`);
  }
  output.push("  }", "", "  public invokeUnary(", "    context: RpcInvocationContext,", "    serviceId: string,", "    methodId: string,", "    request: JsonValue,", "  ): Promise<JsonValue> | JsonValue {");
  for (let serviceIndex = 0; serviceIndex < model.services.length; serviceIndex++) {
    const service = model.services[serviceIndex];
    if (service === undefined) continue;
    for (const method of service.methods) {
      if (method.descriptor.kind !== "unary") continue;
      const request = referenceType(schemaReference(method.descriptor.requestSchema), model);
      output.push(
        `    if (serviceId === ${stringLiteral(service.descriptor.serviceId)} && methodId === ${stringLiteral(method.descriptor.methodId)}) {`,
        `      return this.#service${serviceIndex + 1}.${method.methodName}(request as ${request}, context);`,
        "    }",
      );
    }
  }
  output.push(
    "    throw new Error(`Unknown unary RPC method '${serviceId}/${methodId}' for contract '${CONTRACT_ID}'.`);",
    "  }",
    "",
    "  public invokeServerStream(",
    "    context: RpcInvocationContext,",
    "    serviceId: string,",
    "    methodId: string,",
    "    request: JsonValue,",
    "  ): AsyncIterable<JsonValue> {",
  );
  for (let serviceIndex = 0; serviceIndex < model.services.length; serviceIndex++) {
    const service = model.services[serviceIndex];
    if (service === undefined) continue;
    for (const method of service.methods) {
      if (method.descriptor.kind !== "server-stream") continue;
      const request = referenceType(schemaReference(method.descriptor.requestSchema), model);
      output.push(
        `    if (serviceId === ${stringLiteral(service.descriptor.serviceId)} && methodId === ${stringLiteral(method.descriptor.methodId)}) {`,
        `      return this.#service${serviceIndex + 1}.${method.methodName}(request as ${request}, context);`,
        "    }",
      );
    }
  }
  output.push(
    "    throw new Error(`Unknown server-stream RPC method '${serviceId}/${methodId}' for contract '${CONTRACT_ID}'.`);",
    "  }",
    "}",
    "",
  );
}

function emitProviderRegistrationFactory(
  output: string[],
  model: GeneratorModel,
): void {
  output.push(
    `export function ${model.providerRegistrationFactoryName}(`,
    "  providerId: string,",
  );
  for (const [index, service] of model.services.entries()) {
    output.push(`  service${index + 1}: ${service.providerTypeName},`);
  }
  output.push(
    "): RpcProviderRegistration {",
    "  return {",
    "    ...CONTRACT_IDENTITY,",
    "    providerId,",
    "    declaredErrors: {",
  );
  for (const service of model.services) {
    output.push(`      ${stringLiteral(service.descriptor.serviceId)}: {`);
    for (const method of service.methods) {
      output.push(`        ${stringLiteral(method.descriptor.methodId)}: ${JSON.stringify(method.descriptor.errors ?? [])},`);
    }
    output.push("      },");
  }
  output.push(
    "    },",
    `    handler: new ${model.handlerTypeName}(${model.services.map((_service, index) => `service${index + 1}`).join(", ")}),`,
    "  };",
    "}",
    "",
  );
}

function typeName(
  schema: Schema,
  model: GeneratorModel,
): string {
  if (typeof schema.$ref === "string") return referenceType(schema.$ref, model);
  if (schema.logicalType === "content-reference") return "RpcContentReference";
  if (schema.logicalType === "uuid" || schema.logicalType === "utc-date-time") return "string";
  const literal = literalSchemaType(schema);
  if (literal !== undefined) return literal;
  if (Array.isArray(schema.oneOf)) {
    const variants: string[] = [];
    for (const variant of schema.oneOf) {
      if (!isObject(variant)) return "JsonValue";
      variants.push(typeName(variant, model));
    }
    return unionType(variants);
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return isObject(schema.items) ? `ReadonlyArray<${typeName(schema.items, model)}>` : "ReadonlyArray<JsonValue>";
    case "object":
      if (isObject(schema.additionalProperties)) {
        return `Readonly<Record<string, ${typeName(schema.additionalProperties, model)}>>`;
      }
      return isRecordSchema(schema) ? inlineRecordType(schema, model) : "JsonValue";
    default:
      return "JsonValue";
  }
}

function referenceType(
  reference: string,
  model: GeneratorModel,
): string {
  const prefix = "#/$defs/";
  if (!reference.startsWith(prefix)) return "JsonValue";
  return model.definitionNames.get(reference.slice(prefix.length)) ?? "JsonValue";
}

function literalSchemaType(schema: Schema): string | undefined {
  if (hasOwn(schema, "const")) return literalType(schema.const ?? null);
  if (Array.isArray(schema.enum)) return unionType(schema.enum.map((value) => literalType(value)));
  return undefined;
}

function literalType(value: JsonValue): string {
  if (value === null) return "null";
  if (typeof value === "string") return stringLiteral(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return "JsonValue";
}

function unionType(types: readonly string[]): string {
  const unique = [...new Set(types)];
  if (unique.length === 0 || unique.includes("JsonValue")) return "JsonValue";
  return unique.join(" | ");
}

function inlineRecordType(schema: RecordSchema, model: GeneratorModel): string {
  const required = requiredProperties(schema);
  const properties: string[] = [];
  for (const propertyName of Object.keys(schema.properties).sort(ordinal)) {
    const propertySchema = schema.properties[propertyName];
    if (!isObject(propertySchema)) continue;
    properties.push(`readonly ${propertyIdentifier(propertyName)}${required.has(propertyName) ? "" : "?"}: ${typeName(propertySchema, model)};`);
  }
  return properties.length === 0 ? "{}" : `{ ${properties.join(" ")} }`;
}

function requiredProperties(schema: Schema): ReadonlySet<string> {
  return new Set(Array.isArray(schema.required)
    ? schema.required.filter((value): value is string => typeof value === "string")
    : []);
}

function isRecordSchema(schema: Schema): schema is RecordSchema {
  return schema.type === "object"
    && schema.additionalProperties === false
    && isObject(schema.properties);
}

function schemaReference(value: string | RpcSchemaReference | undefined): string {
  if (typeof value === "string") return value;
  if (value !== undefined && typeof value.$ref === "string") return value.$ref;
  throw new TypeError("RPC method schema must be a local definition reference.");
}

function services(descriptor: RpcContractDescriptor): GeneratorServiceDescriptor[] {
  if (descriptor.descriptorVersion === 2) {
    return Object.entries(descriptor.services).map(([serviceId, service]) => ({
      serviceId,
      methods: Object.entries(service.methods).map(([methodId, method]) => ({ ...method, methodId })),
    }));
  }
  const values = Array.isArray(descriptor.services)
    ? [...descriptor.services]
    : Object.entries(descriptor.services).map(([serviceId, service]) => ({ ...service, serviceId }));
  return values.map((service) => ({
    serviceId: service.serviceId,
    methods: Array.isArray(service.methods)
      ? [...service.methods]
      : Object.entries(service.methods as Readonly<Record<string, GeneratorMethodDescriptor>>)
        .map(([methodId, method]) => ({ ...method, methodId })),
  }));
}

function identifier(value: string): string {
  let output = "";
  let capitalize = true;
  for (const character of value) {
    if (!/[A-Za-z0-9]/u.test(character)) {
      capitalize = true;
      continue;
    }
    output += capitalize ? character.toUpperCase() : character;
    capitalize = false;
  }
  if (output.length === 0) output = "Value";
  if (/^[0-9]/u.test(output)) output = `_${output}`;
  return output;
}

function propertyIdentifier(value: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(value) ? value : stringLiteral(value);
}

function stringLiteral(value: string): string {
  return JSON.stringify(value)
    .replace(/\u2028/gu, "\\u2028")
    .replace(/\u2029/gu, "\\u2029");
}

function hasOwn(object: Schema, name: string): boolean {
  return Object.prototype.hasOwnProperty.call(object, name);
}

function isObject(value: unknown): value is Readonly<Record<string, JsonValue>> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function schemaUsesContentReference(value: JsonValue): boolean {
  if (Array.isArray(value)) return value.some(schemaUsesContentReference);
  if (!isObject(value)) return false;
  if (value.logicalType === "content-reference") return true;
  return Object.values(value).some(schemaUsesContentReference);
}

class SymbolAllocator {
  readonly #used = new Set<string>();

  public reserve(value: string): void {
    this.#used.add(value);
  }

  public allocate(preferred: string): string {
    if (!this.#used.has(preferred)) {
      this.#used.add(preferred);
      return preferred;
    }
    for (let suffix = 2; ; suffix++) {
      const candidate = `${preferred}${suffix}`;
      if (this.#used.has(candidate)) continue;
      this.#used.add(candidate);
      return candidate;
    }
  }
}

function ordinal(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}
