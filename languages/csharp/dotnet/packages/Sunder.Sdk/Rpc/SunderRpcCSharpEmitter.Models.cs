using System.Globalization;
using System.Text;

namespace Sunder.Sdk.Rpc;

internal static partial class SunderRpcCSharpEmitter
{
    internal static string EmitModels(SunderRpcCSharpGeneratorModel model, string modelsNamespace, string codecNamespace)
    {
        model = model with { ProjectedRecords = true };
        var declarations = new StringBuilder();
        var codecs = new StringBuilder();
        foreach (var definition in model.Definitions)
            EmitDefinition(declarations, definition, model, codecs, modelsNamespace, codecNamespace);
        return ("// <auto-generated />\n#nullable enable\nnamespace " + modelsNamespace + " {\n" + declarations + "}\nnamespace "
            + codecNamespace + " {\n" + codecs + "}\n").Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    internal static string EmitTransport(SunderRpcCSharpGeneratorModel model, string namespaceName)
        => Emit(model with { Definitions = [] }, namespaceName);

    private static string Qualified(string? ns, string name)
        => ns is null || name.StartsWith("global::", StringComparison.Ordinal) ? name : "global::" + ns + "." + name;

    private static void EmitNumericEnumDefinition(StringBuilder output, SunderRpcCSharpNumericEnumDefinitionModel definition,
        SunderRpcCSharpGeneratorModel model, StringBuilder? codecs, string? modelsNamespace, string? codecNamespace)
    {
        var type = Qualified(modelsNamespace, definition.TypeName);
        output.Append("[global::System.Text.Json.Serialization.JsonConverter(typeof(").Append(Qualified(codecNamespace, definition.ConverterTypeName))
            .AppendLine("))]").Append(model.Accessibility).Append(" enum ").Append(definition.TypeName).AppendLine(" : long {");
        foreach (var value in definition.Values) output.Append("    ").Append(NumericName(value)).Append(" = ").Append(value.ToString(CultureInfo.InvariantCulture)).AppendLine("L,");
        output.AppendLine("}");
        output = codecs ?? output;
        output.Append("internal sealed class ").Append(definition.ConverterTypeName).Append(" : global::System.Text.Json.Serialization.JsonConverter<").Append(type).AppendLine("> {")
            .Append("    public override ").Append(type).AppendLine(" Read(ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type typeToConvert, global::System.Text.Json.JsonSerializerOptions options) {")
            .AppendLine("        var value = global::System.Text.Json.JsonSerializer.Deserialize<long>(ref reader, options);")
            .AppendLine("        return value switch {");
        foreach (var value in definition.Values) output.Append("            ").Append(value.ToString(CultureInfo.InvariantCulture)).Append("L => ").Append(type).Append('.').Append(NumericName(value)).AppendLine(",");
        output.AppendLine("            _ => throw new global::System.Text.Json.JsonException(\"The numeric enum value is not declared.\"),").AppendLine("        };").AppendLine("    }")
            .Append("    public override void Write(global::System.Text.Json.Utf8JsonWriter writer, ").Append(type).AppendLine(" value, global::System.Text.Json.JsonSerializerOptions options) {")
            .AppendLine("        switch (value) {");
        foreach (var value in definition.Values) output.Append("            case ").Append(type).Append('.').Append(NumericName(value)).Append(": writer.WriteNumberValue(").Append(value.ToString(CultureInfo.InvariantCulture)).AppendLine("L); return;");
        output.AppendLine("            default: throw new global::System.Text.Json.JsonException(\"The numeric enum value is not declared.\");")
            .AppendLine("        }").AppendLine("    }").AppendLine("}");
    }

    private static string NumericName(long value)
        => value < 0 ? "ValueNegative" + (-value).ToString(CultureInfo.InvariantCulture) : "Value" + value.ToString(CultureInfo.InvariantCulture);

    private static void EmitTransparentDefinition(StringBuilder output, SunderRpcCSharpTransparentDefinitionModel definition,
        SunderRpcCSharpGeneratorModel model, StringBuilder? codecs, string? modelsNamespace, string? codecNamespace)
    {
        var type = Qualified(modelsNamespace, definition.TypeName);
        output.Append("[global::System.Text.Json.Serialization.JsonConverter(typeof(").Append(Qualified(codecNamespace, definition.ConverterTypeName)).AppendLine("))]")
            .Append(model.Accessibility).Append(" readonly record struct ").Append(definition.TypeName).Append('(').Append(definition.ValueTypeName).AppendLine(" Value);");
        output = codecs ?? output;
        output.Append("internal sealed class ").Append(definition.ConverterTypeName).Append(" : global::System.Text.Json.Serialization.JsonConverter<").Append(type).AppendLine("> {")
            .AppendLine("    public override bool HandleNull => true;")
            .Append("    public override ").Append(type).AppendLine(" Read(ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type typeToConvert, global::System.Text.Json.JsonSerializerOptions options)")
            .Append("        => new(global::System.Text.Json.JsonSerializer.Deserialize<").Append(definition.ValueTypeName).AppendLine(">(ref reader, options)!);")
            .Append("    public override void Write(global::System.Text.Json.Utf8JsonWriter writer, ").Append(type).AppendLine(" value, global::System.Text.Json.JsonSerializerOptions options)")
            .Append("        => global::System.Text.Json.JsonSerializer.Serialize<").Append(definition.ValueTypeName).AppendLine(">(writer, value.Value, options);")
            .AppendLine("}");
    }
}
