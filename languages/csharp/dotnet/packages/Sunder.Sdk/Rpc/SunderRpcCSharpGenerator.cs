            .AppendLine("            new global::System.Collections.Generic.Dictionary<string, global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>>(global::System.StringComparer.Ordinal)")
            .AppendLine("            {");
        foreach (var service in model.Services)
        {
            output.Append("                [\"").Append(EscapeStringLiteral(service.Descriptor.ServiceId)).AppendLine("\"] =")
                .AppendLine("                    new global::System.Collections.ObjectModel.ReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>(")
                .AppendLine("                        new global::System.Collections.Generic.Dictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>(global::System.StringComparer.Ordinal)")
                .AppendLine("                        {");
            foreach (var method in service.Methods)
            {
                output.Append("                            [\"").Append(EscapeStringLiteral(method.Descriptor.MethodId)).Append("\"] = ");
                if (method.Descriptor.Errors.Count == 0)
                {
                    output.AppendLine("global::System.Array.Empty<string>(),");
                }
                else
                {
                    output.Append("global::System.Array.AsReadOnly(new string[] { ");
                    for (var index = 0; index < method.Descriptor.Errors.Count; index++)
                    {
                        if (index > 0) output.Append(", ");
                        output.Append('"').Append(EscapeStringLiteral(method.Descriptor.Errors[index])).Append('"');
                    }
                    output.AppendLine(" }),");
                }
            }
            output.AppendLine("                        }),");
        }
        output.AppendLine("            });")
            .AppendLine();
    }

    private static string GetTypeName(JsonElement schema, GeneratorModel model)
    {
        if (schema.TryGetProperty("$ref", out var reference))
        {
            return ReferenceType(reference.GetString()!, model);
        }
        if (model.IsV2 && schema.TryGetProperty("logicalType", out var logicalType))
        {
            return logicalType.GetString() switch
            {
                "uuid" => "global::System.Guid",
                "utc-date-time" => "string",
                "content-reference" => "global::Sunder.Sdk.Rpc.SunderRpcContentReference",
                _ => "global::System.Text.Json.JsonElement",
            };
        }
        if (schema.TryGetProperty("oneOf", out var oneOf))
        {
            var variants = oneOf.EnumerateArray().ToArray();
            if (variants.Length == 2)
            {
                var nullCount = variants.Count(variant => IsNullSchema(variant, model));
                if (nullCount == 1)
                {
                    var valueSchema = variants.Single(variant => !IsNullSchema(variant, model));
                    return MakeNullable(GetTypeName(valueSchema, model));
                }
            }
            return "global::System.Text.Json.JsonElement";
        }

        return schema.GetProperty("type").GetString() switch
        {
            "string" => "string",
            "integer" => "long",
            "number" => model.IsV2 ? "double" : "decimal",
            "boolean" => "bool",
            "null" => "object?",
            "array" => "global::System.Collections.Generic.IReadOnlyList<" + GetTypeName(schema.GetProperty("items"), model) + ">",
            "object" when schema.GetProperty("additionalProperties").ValueKind == JsonValueKind.Object
                => "global::System.Collections.Generic.IReadOnlyDictionary<string, "
                   + GetTypeName(schema.GetProperty("additionalProperties"), model)
                   + ">",
            _ => "global::System.Text.Json.JsonElement",
        };
    }

    private static string ReferenceType(string reference, GeneratorModel model)
    {
        var name = reference["#/$defs/".Length..];
        var schema = model.Schemas[name];
        var visited = new HashSet<string>(StringComparer.Ordinal);
        while (schema.TryGetProperty("$ref", out var nestedReference))
        {
            if (!visited.Add(name)) return "global::System.Text.Json.JsonElement";
            name = nestedReference.GetString()!["#/$defs/".Length..];
            schema = model.Schemas[name];
        }
        return model.RecordNames.TryGetValue(name, out var recordName)
            ? recordName
            : GetTypeName(schema, model);
    }

    private static bool ReferenceAllowsNull(string reference, GeneratorModel model)
    {
        SunderRpcDescriptorParser.TryGetReferenceName(reference, out var name);
        return SchemaAllowsNull(model.Schemas[name], model);
    }

    private static bool SchemaAllowsNull(JsonElement schema, GeneratorModel model)
        => SchemaAllowsNull(schema, model, new HashSet<string>(StringComparer.Ordinal));

    private static bool SchemaAllowsNull(
        JsonElement schema,
        GeneratorModel model,
        HashSet<string> referenceStack)
    {
        if (schema.TryGetProperty("$ref", out var reference))
        {
            SunderRpcDescriptorParser.TryGetReferenceName(reference.GetString(), out var name);
            if (!referenceStack.Add(name)) return false;
            var allowsNull = SchemaAllowsNull(model.Schemas[name], model, referenceStack);
            referenceStack.Remove(name);
            return allowsNull;
        }
        if (schema.TryGetProperty("type", out var type) && type.GetString() == "null")
        {
            return true;
        }
        return schema.TryGetProperty("oneOf", out var oneOf)
               && oneOf.EnumerateArray().Count(variant =>
                   SchemaAllowsNull(variant, model, referenceStack)) == 1;
    }

    private static bool IsNullSchema(JsonElement schema, GeneratorModel model)
    {
        var visited = new HashSet<string>(StringComparer.Ordinal);
        while (schema.TryGetProperty("$ref", out var reference))
        {
            SunderRpcDescriptorParser.TryGetReferenceName(reference.GetString(), out var name);
            if (!visited.Add(name)) return false;
            schema = model.Schemas[name];
        }
        return schema.TryGetProperty("type", out var type) && type.GetString() == "null";
    }

    private static bool IsRecordSchema(JsonElement schema)
        => schema.TryGetProperty("type", out var type)
           && type.GetString() == "object"
           && schema.TryGetProperty("properties", out _)
           && schema.GetProperty("additionalProperties").ValueKind == JsonValueKind.False;

    private static string MakeNullable(string typeName)
        => typeName.EndsWith("?", StringComparison.Ordinal) ? typeName : typeName + "?";

    private static string ContractIdentityTypeName(SunderRpcContractDescriptor descriptor)
    {
        var identity = Encoding.UTF8.GetBytes(descriptor.ContractId + "\0" + descriptor.Version);
        return "SunderRpcContractIdentity_"
               + Convert.ToHexString(SHA256.HashData(identity)).ToLowerInvariant();
    }

    private static string Identifier(string value)
    {
        var output = new StringBuilder();
        var capitalize = true;
        foreach (var character in value)
        {
            if (!char.IsAsciiLetterOrDigit(character))
            {
                capitalize = true;
                continue;
            }
            output.Append(capitalize ? char.ToUpperInvariant(character) : character);
            capitalize = false;
        }
        if (output.Length == 0) output.Append("Value");
        if (char.IsAsciiDigit(output[0])) output.Insert(0, '_');
        return EscapeIdentifier(output.ToString());
    }

    private static string EscapeIdentifier(string value)
        => CSharpKeywords.Contains(value) ? "@" + value : value;

    private static string EscapeNamespace(string value)
        => string.Join('.', value.Split('.').Select(EscapeIdentifier));

    private static bool IsNamespace(string value)
        => !string.IsNullOrWhiteSpace(value)
           && value.Length <= 512
           && value.Split('.').All(static segment => segment.Length > 0
               && (char.IsAsciiLetter(segment[0]) || segment[0] == '_')
               && segment.All(static character => char.IsAsciiLetterOrDigit(character) || character == '_'));

    private static string EscapeStringLiteral(string value)
    {
        var output = new StringBuilder(value.Length);
        foreach (var character in value)
        {
            switch (character)
            {
                case '\\': output.Append("\\\\"); break;
                case '"': output.Append("\\\""); break;
                case '\0': output.Append("\\0"); break;
                case '\a': output.Append("\\a"); break;
                case '\b': output.Append("\\b"); break;
                case '\f': output.Append("\\f"); break;
                case '\n': output.Append("\\n"); break;
                case '\r': output.Append("\\r"); break;
                case '\t': output.Append("\\t"); break;
                case '\v': output.Append("\\v"); break;
                default:
                    if (char.IsControl(character) || character is '\u2028' or '\u2029')
                    {
                        output.Append("\\u").Append(((int)character).ToString("x4", System.Globalization.CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        output.Append(character);
                    }
                    break;
            }
        }
        return output.ToString();
    }

    private sealed class SymbolAllocator
    {
        private readonly HashSet<string> _used = new(StringComparer.Ordinal);

        public void Reserve(string value) => _used.Add(value);

        public string Allocate(string preferred)
        {
            preferred = EscapeIdentifier(preferred);
            if (_used.Add(preferred)) return preferred;
            var unescaped = preferred.StartsWith('@') ? preferred[1..] : preferred;
            for (var suffix = 2; ; suffix++)
            {
                var candidate = EscapeIdentifier(unescaped + suffix.ToString(System.Globalization.CultureInfo.InvariantCulture));
                if (_used.Add(candidate)) return candidate;
            }
        }
    }

