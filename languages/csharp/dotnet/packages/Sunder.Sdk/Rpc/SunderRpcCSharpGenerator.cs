            .AppendLine("(global::Sunder.Sdk.Rpc.ISunderRpcCallScope scope, global::Sunder.Sdk.Rpc.SunderRpcEndpointReference endpoint)")
            .AppendLine("    {")
            .AppendLine("        _scope = scope ?? throw new global::System.ArgumentNullException(nameof(scope));")
            .AppendLine("        _endpoint = endpoint ?? throw new global::System.ArgumentNullException(nameof(endpoint));")
            .AppendLine("    }").AppendLine();
