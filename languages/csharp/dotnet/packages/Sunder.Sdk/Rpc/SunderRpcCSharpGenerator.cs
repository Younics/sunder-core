        output.Append("public sealed class ").Append(service.ClientTypeName).AppendLine().AppendLine("{");
        output.AppendLine("    private readonly global::Sunder.Sdk.Rpc.ISunderRpcCallScope _scope;");
        output.AppendLine("    private readonly global::Sunder.Sdk.Rpc.SunderRpcEndpointReference _endpoint;").AppendLine();
