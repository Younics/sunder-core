using System.Text;
using Sunder.Sdk.Rpc;

namespace Sunder.Package.Build.Rpc.Authoring.CSharp;

internal static partial class SunderRpcCSharpImplementationEmitter
{
    // Core-only callers own their call scope. All transport identity, methods and
    // wire types come from the same checked descriptor as the generated provider.
    internal static string EmitCorePlatformClient(SunderRpcCSharpPlatformAdapter adapter)
    {
        var contract = adapter.Surface.Contract;
        var model = SunderRpcCSharpGeneratorModelBuilder.Build(contract.Descriptor, "internal");
        var service = model.Services.Single();
        var output = new StringBuilder("// <auto-generated />\n#nullable enable\n");
        EmitPlatformAdapterSchema(output, contract);
        output.Append("namespace ").Append(EscapeNamespace(contract.GeneratedLogicalName)).AppendLine("\n{")
            .AppendLine("    internal static class CoreStackContract\n    {")
            .Append("        internal const string ContractId = \"").Append(EscapeString(contract.Descriptor.ContractId)).AppendLine("\";")
            .AppendLine("        internal static global::Sunder.Sdk.Rpc.SunderRpcContractDescriptor Descriptor => __SunderPlatformAdapterSchema.Descriptor;")
            .AppendLine("    }")
            .AppendLine("    internal sealed class StackDomainClient\n    {")
            .Append("        private readonly ").Append(service.ClientTypeName).AppendLine(" _wire;")
            .AppendLine("        internal StackDomainClient(global::Sunder.Sdk.Rpc.ISunderRpcCallScope scope, global::Sunder.Sdk.Rpc.SunderRpcEndpointReference endpoint)")
            .AppendLine("            => _wire = new(scope, endpoint);");
        foreach (var mapping in adapter.Methods)
        {
            var method = service.Methods.Single(value => value.MethodId == mapping.Descriptor.MethodId);
            output.Append("        internal async global::System.Threading.Tasks.ValueTask");
            if (mapping.OutputType is not null) output.Append('<').Append(mapping.OutputType.ToDisplayString(TypeDisplayFormat)).Append('>');
            output.Append(' ').Append(EscapeIdentifier(mapping.Method.Name)).Append('(');
            if (mapping.RequestType is not null) output.Append(mapping.RequestType.ToDisplayString(TypeDisplayFormat)).Append(" request, ");
            output.AppendLine("global::System.Threading.CancellationToken cancellationToken = default)\n        {")
                .AppendLine("            cancellationToken.ThrowIfCancellationRequested();")
                .Append("            var response = await _wire.").Append(method.MethodName).Append('(');
            if (mapping.RequestType is null) output.Append("new ").Append(method.RequestTypeName).Append("()");
            else output.Append("__SunderPlatformAdapterSchema.Convert<").Append(method.RequestTypeName)
                .Append(">(__SunderPlatformAdapterSchema.Serialize(request, \"").Append(EscapeString(mapping.Descriptor.RequestSchemaReference))
                .Append("\"), \"").Append(EscapeString(mapping.Descriptor.RequestSchemaReference)).Append("\")");
            output.AppendLine(", cancellationToken).ConfigureAwait(false);")
                .Append("            var result = __SunderPlatformAdapterSchema.Serialize(response, \"").Append(EscapeString(mapping.Descriptor.OutputSchemaReference)).AppendLine("\");");
            if (mapping.OutputType is not null) output.Append("            return __SunderPlatformAdapterSchema.Convert<")
                .Append(mapping.OutputType.ToDisplayString(TypeDisplayFormat)).Append(">(result, \"")
                .Append(EscapeString(mapping.Descriptor.OutputSchemaReference)).AppendLine("\");");
            output.AppendLine("        }");
        }
        output.AppendLine("    }\n}");
        return output.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }
}
