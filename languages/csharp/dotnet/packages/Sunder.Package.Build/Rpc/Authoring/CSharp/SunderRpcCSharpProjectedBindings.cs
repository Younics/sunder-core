using System.Collections.ObjectModel;
using System.Text.Json;
using Sunder.Package.Format;
using Sunder.Sdk.Rpc;

namespace Sunder.Package.Build.Rpc.Authoring.CSharp;

internal sealed record SunderRpcCSharpProjectionInput(string AuthorityPackageId, string TransportNamespace,
    SunderRpcContractDescriptor Descriptor, SunderRpcModelProjection ModelProjection, bool PublicModels = true)
{
    internal SunderRpcMethodPolicies MethodPolicies { get; init; } = SunderRpcMethodPolicies.Empty;
}

internal sealed record SunderRpcCSharpProjectionBinding(SunderRpcCSharpProjectionInput Input,
    IReadOnlyDictionary<string, SunderRpcCSharpTypeBinding> Types, SunderRpcCSharpGeneratorModel Model);

internal sealed record SunderRpcCSharpProjectedBindingSet(IReadOnlyDictionary<string, SunderRpcCSharpProjectionBinding> Contracts,
    IReadOnlyList<SunderRpcCSharpSourceFile> Sources);

// Consumes authenticated projection metadata. A schema/name coincidence is never
// a reason to share a declaration; only (authority, projected model name) is.
internal static class SunderRpcCSharpProjectedBindings
{
    internal static string SchemaSource(string ns, SunderRpcContractDescriptor descriptor)
        => "// <auto-generated />\n#nullable enable\nnamespace " + ns + ";\ninternal static class __SunderContract {\n"
            + "    internal static global::Sunder.Sdk.Rpc.SunderRpcContractDescriptor Descriptor { get; } = global::Sunder.Sdk.Rpc.SunderRpcContractDescriptor.Parse(global::System.Convert.FromBase64String(\""
            + Convert.ToBase64String(descriptor.GetCanonicalUtf8()) + "\"));\n}\n";

    internal static SunderRpcCSharpProjectedBindingSet Generate(IReadOnlyList<SunderRpcCSharpProjectionInput> inputs)
    {
        var byId = inputs.ToDictionary(input => input.Descriptor.ContractId, StringComparer.Ordinal);
        SunderRpcModelProjectionGraph.Validate(inputs.Select(input => new SunderRpcModelProjectionContract(input.Descriptor.ContractId,
                input.Descriptor.Version, input.Descriptor.Sha256, input.Descriptor.AbiSha256, input.ModelProjection, input.MethodPolicies)).ToArray(),
            byId.ToDictionary(pair => pair.Key, pair => pair.Value.Descriptor, StringComparer.Ordinal),
            byId.ToDictionary(pair => pair.Key, pair => "package:" + pair.Value.AuthorityPackageId, StringComparer.Ordinal));
        var bindings = new Dictionary<string, SunderRpcCSharpProjectionBinding>(StringComparer.Ordinal);
        var emitted = new Dictionary<string, (string Identity, string Source)>(StringComparer.OrdinalIgnoreCase);
        var symbolOwners = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        var publicModels = inputs.Where(input => input.PublicModels).SelectMany(input => input.ModelProjection.Models.Values.Select(name => input.AuthorityPackageId + "/" + name)).ToHashSet(StringComparer.Ordinal);
        var sources = new List<SunderRpcCSharpSourceFile>();
        foreach (var input in inputs.OrderBy(input => input.Descriptor.ContractId, StringComparer.Ordinal))
        {
            var types = new Dictionary<string, SunderRpcCSharpTypeBinding>(StringComparer.Ordinal);
            var modelDeclarations = new HashSet<string>(StringComparer.Ordinal);
            var modelsNamespace = Editor.GeneratedPackageNames.Models(input.AuthorityPackageId);
            var reachable = SunderRpcCSharpModelProjection.ReachableDefinitions(input.Descriptor);
            foreach (var (definition, schema) in input.Descriptor.Definitions.Where(pair => reachable.Contains(pair.Key)).OrderBy(pair => pair.Key, StringComparer.Ordinal))
            {
                if (input.ModelProjection.ServiceReferences.TryGetValue(definition, out var reference))
                {
                    if (!byId.TryGetValue(reference.ContractId, out var target)) throw new InvalidDataException("rpc-authoring.model-projection-invalid: The service reference target is not selected.");
                    var serviceType = Editor.GeneratedPackageNames.ServiceInterface(target.AuthorityPackageId, reference.ServiceId);
                    types.Add(definition, new("global::Sunder.Sdk.Services.ServiceReference<global::" + serviceType + ">", null));
                    continue;
                }
                var mapped = input.ModelProjection.Models.TryGetValue(definition, out var modelName);
                if (!mapped && !NeedsDeclaration(schema)) continue;
                modelName ??= Editor.GeneratedPackageNames.ContractSymbol(input.Descriptor.ContractId) + "_" + SunderRpcCSharpSyntax.Identifier(definition).TrimStart('@');
                types.Add(definition, new("global::" + modelsNamespace + "." + SunderRpcCSharpSyntax.EscapeIdentifier(modelName),
                    mapped && !modelDeclarations.Add(modelName) ? null : modelName));
            }
            var immutableTypes = new ReadOnlyDictionary<string, SunderRpcCSharpTypeBinding>(types);
            var model = SunderRpcCSharpGeneratorModelBuilder.Build(input.Descriptor, "internal", immutableTypes, modelsNamespace,
                "global::Sunder.Sdk.Services.SunderContent", reachable);
            bindings.Add(input.Descriptor.ContractId, new(input, immutableTypes, model));
        }
        NormalizeSharedRecords(bindings, publicModels);
        foreach (var binding in bindings.Values.OrderBy(binding => binding.Input.Descriptor.ContractId, StringComparer.Ordinal))
        {
            var input = binding.Input;
            var model = binding.Model;
            var modelsNamespace = Editor.GeneratedPackageNames.Models(input.AuthorityPackageId);
            foreach (var definition in model.Definitions)
            {
                var identity = input.ModelProjection.Models.TryGetValue(definition.DefinitionName, out var modelName)
                    ? "model:" + input.AuthorityPackageId + "/" + modelName
                    : definition.OwnerDefinitionName is { } owner && input.ModelProjection.Models.TryGetValue(owner, out var ownerModel)
                        ? "model:" + input.AuthorityPackageId + "/" + ownerModel + "/inline:" + definition.TypeName
                        : "synthetic:" + input.Descriptor.ContractId + "/" + definition.DefinitionName;
                var publicModel = IsPublic(input, definition, publicModels);
                var source = SunderRpcCSharpEmitter.EmitModels(model with { Accessibility = publicModel ? "public" : "internal", Definitions = [definition] },
                    modelsNamespace, Editor.GeneratedPackageNames.Internal(input.AuthorityPackageId));
                var symbol = modelsNamespace + "." + definition.TypeName.TrimStart('@');
                Reserve(symbol, identity);
                if (definition is SunderRpcCSharpTaggedUnionDefinitionModel union)
                    foreach (var variant in union.Variants.Where(variant => variant.SyntheticRecord is not null))
                        Reserve(modelsNamespace + "." + variant.TypeName.TrimStart('@'), identity + "/variant:" + variant.Tag);
                if (emitted.TryGetValue(symbol, out var previous))
                {
                    if (previous.Identity != identity || previous.Source != source)
                        throw new InvalidDataException($"rpc-authoring.generated-name-collision: '{symbol}' has distinct source identities or incompatible C# projections ('{previous.Identity}', '{identity}').");
                    continue;
                }
                emitted.Add(symbol, (identity, source));
                sources.Add(new("models/" + input.AuthorityPackageId + "/" + definition.TypeName.TrimStart('@') + ".g.cs", source));
            }
            sources.Add(new("bindings/imports/" + input.Descriptor.ContractId + ".g.cs", SunderRpcCSharpEmitter.EmitTransport(model, input.TransportNamespace)));
            sources.Add(new("bindings/imports/" + input.Descriptor.ContractId + ".schema.g.cs", SchemaSource(input.TransportNamespace, input.Descriptor)));
        }
        return new(new ReadOnlyDictionary<string, SunderRpcCSharpProjectionBinding>(bindings), sources.OrderBy(source => source.Path, StringComparer.Ordinal).ToArray());

        void Reserve(string symbol, string identity)
        {
            if (symbolOwners.TryGetValue(symbol, out var previous) && previous != identity)
                throw new InvalidDataException($"rpc-authoring.generated-name-collision: '{symbol}' has distinct generated identities ('{previous}', '{identity}').");
            symbolOwners[symbol] = identity;
        }
    }

    private static bool IsPublic(SunderRpcCSharpProjectionInput input, SunderRpcCSharpDefinitionModel definition, IReadOnlySet<string> publicModels)
        => input.PublicModels || input.ModelProjection.Models.TryGetValue(definition.OwnerDefinitionName ?? definition.DefinitionName, out var name)
            && publicModels.Contains(input.AuthorityPackageId + "/" + name);

    // A shared variant may be used directly by another contract which does not
    // mention its union. Its CLR declaration still has to be identical in both.
    // Decide inheritance over the complete projection set, not a local descriptor.
    private static void NormalizeSharedRecords(Dictionary<string, SunderRpcCSharpProjectionBinding> bindings, IReadOnlySet<string> publicModels)
    {
        string Symbol(SunderRpcCSharpProjectionBinding binding, string name)
            => "global::" + Editor.GeneratedPackageNames.Models(binding.Input.AuthorityPackageId) + "." + name;
        var records = bindings.Values.SelectMany(binding => binding.Model.Definitions.OfType<SunderRpcCSharpRecordDefinitionModel>()
            .Select(record => (Binding: binding, Definition: record, Symbol: Symbol(binding, record.TypeName)))).ToArray();
        var parents = records.Where(record => record.Definition.Record.BaseTypeName is not null)
            .GroupBy(record => record.Symbol, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Select(record => Symbol(record.Binding, record.Definition.Record.BaseTypeName!)).Distinct(StringComparer.Ordinal).ToArray(), StringComparer.Ordinal);
        var publicRecords = records.Where(record => IsPublic(record.Binding.Input, record.Definition, publicModels)).Select(record => record.Symbol).ToHashSet(StringComparer.Ordinal);
        var syntheticUnions = bindings.Values.SelectMany(binding => binding.Model.Definitions.OfType<SunderRpcCSharpTaggedUnionDefinitionModel>()
            .Where(union => union.Variants.Any(variant => variant.SyntheticRecord is null
                && (parents.GetValueOrDefault(variant.TypeName)?.Length > 1
                    || publicRecords.Contains(variant.TypeName) && !IsPublic(binding.Input, union, publicModels))))
            .Select(union => Symbol(binding, union.TypeName))).ToHashSet(StringComparer.Ordinal);

        foreach (var (id, binding) in bindings.ToArray())
        {
            var definitions = binding.Model.Definitions.Select(definition =>
            {
                if (definition is SunderRpcCSharpTaggedUnionDefinitionModel union && syntheticUnions.Contains(Symbol(binding, union.TypeName)))
                    return union with { Variants = union.Variants.Select(variant =>
                    {
                        if (variant.SyntheticRecord is not null) return variant;
                        var variantRecord = records.First(candidate => candidate.Symbol == variant.TypeName && candidate.Definition.Record.BaseTypeName == union.TypeName).Definition.Record;
                        var typeName = union.TypeName + SunderRpcCSharpSyntax.Identifier(variant.Tag);
                        if (variantRecord.Properties.Any(property => property.Name.TrimStart('@') == typeName.TrimStart('@')))
                            throw new InvalidDataException($"rpc-authoring.generated-name-collision: Union variant '{typeName}' conflicts with one of its members.");
                        return variant with { TypeName = typeName, SyntheticRecord = variantRecord with { TypeName = typeName, BaseTypeName = union.TypeName } };
                    }).ToArray() };
                if (definition is SunderRpcCSharpRecordDefinitionModel record && record.Record.BaseTypeName is { } parent && syntheticUnions.Contains(Symbol(binding, parent)))
                    return record with { Record = record.Record with { BaseTypeName = null, Properties = record.Record.Properties.Select(property =>
                        property.ConstantValue is null ? property : property with { ConstantValue = null, IsRequired = true }).ToArray() } };
                return definition;
            }).ToArray();
            bindings[id] = binding with { Model = binding.Model with { Definitions = definitions } };
        }

        var shared = bindings.Values.SelectMany(binding => binding.Model.Definitions.OfType<SunderRpcCSharpRecordDefinitionModel>()
                .Where(record => record.Record.BaseTypeName is not null).Select(record => (Symbol: Symbol(binding, record.TypeName), record.Record)))
            .GroupBy(record => record.Symbol, StringComparer.Ordinal).ToDictionary(group => group.Key, group => group.First().Record, StringComparer.Ordinal);
        foreach (var (id, binding) in bindings.ToArray())
            bindings[id] = binding with { Model = binding.Model with { Definitions = binding.Model.Definitions.Select(definition =>
                definition is SunderRpcCSharpRecordDefinitionModel record && shared.TryGetValue(Symbol(binding, record.TypeName), out var canonical)
                    ? record with { Record = record.Record with { BaseTypeName = canonical.BaseTypeName, Properties = record.Record.Properties.Select(property =>
                        canonical.Properties.Single(candidate => candidate.WireName == property.WireName) is { ConstantValue: not null } tag
                            ? property with { ConstantValue = tag.ConstantValue, IsRequired = tag.IsRequired, Serialization = tag.Serialization } : property).ToArray() } }
                    : definition).ToArray() } };
    }

    private static bool NeedsDeclaration(JsonElement schema)
        => schema.TryGetProperty("properties", out _) && schema.TryGetProperty("additionalProperties", out var additional) && additional.ValueKind == JsonValueKind.False
            || schema.TryGetProperty("type", out var type) && type.GetString() == "string" && schema.TryGetProperty("enum", out _)
            || schema.TryGetProperty("oneOf", out var variants) && variants.EnumerateArray().All(variant => !variant.TryGetProperty("type", out var kind) || kind.GetString() != "null");
}
