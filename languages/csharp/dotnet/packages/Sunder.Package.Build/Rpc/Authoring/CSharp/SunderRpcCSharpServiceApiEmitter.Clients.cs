    internal static IReadOnlyList<SunderRpcCSharpSourceFile> EmitAppClients(IReadOnlyList<SunderRpcCSharpCompiledContract> contracts, string packageId, string packageVersion,
        bool providerSchemasPresent = false)
    {
        var files = new List<SunderRpcCSharpSourceFile> { new("service-client-lifetime.g.cs", EmitLifetime(packageId)) };
        foreach (var contract in contracts.OrderBy(value => value.ContractKey, StringComparer.Ordinal))
        {
            var output = new StringBuilder("// <auto-generated />\n#nullable enable\nusing global::System.Threading.Tasks;\n");
            if (!providerSchemasPresent || contract.Providers.Count == 0)
                SunderRpcCSharpImplementationEmitter.EmitServiceClientSchema(output, contract);
            var name = SunderRpcCSharpImportPrepass.ContractName(contract.Descriptor.ContractId) + "Client";
            output.Append("namespace ").Append(Editor.GeneratedPackageNames.Internal(packageId)).AppendLine(" {")
                .Append("internal sealed class ").Append(name).Append(" : ").Append(ApiType(contract))
                .AppendLine(", global::System.IDisposable, global::System.IAsyncDisposable {")
                .AppendLine("    private readonly ServiceClientLifetime __lifetime;")
                .AppendLine("    private readonly global::Sunder.Sdk.Rpc.SunderRpcProviderSnapshot? __selectedProvider;")
                .AppendLine("    private readonly bool __ownsLifetime;")
                .AppendLine("    private readonly global::System.IServiceProvider? __services;")
                .AppendLine("    private readonly global::System.Threading.CancellationToken __providerRetirement;")
                .Append("    public ").Append(name).AppendLine("(global::Sunder.Sdk.Rpc.ISunderRpcClient rpc) : this(rpc, null) { }")
                .Append("    public ").Append(name).AppendLine("(global::Sunder.Sdk.Rpc.ISunderRpcClient rpc, global::System.IServiceProvider? services) { __lifetime = new(rpc, services?.GetService(typeof(global::Sunder.Sdk.Rpc.SunderRpcServiceBindingLifetime)) as global::Sunder.Sdk.Rpc.SunderRpcServiceBindingLifetime); __ownsLifetime = true; __services = services; }")
                .Append("    internal ").Append(name).AppendLine("(ServiceClientLifetime lifetime, global::Sunder.Sdk.Rpc.SunderRpcProviderSnapshot provider, global::System.IServiceProvider? services, global::System.Threading.CancellationToken retirement) { __lifetime = lifetime; __selectedProvider = provider; __services = services; __providerRetirement = retirement; }")
                .Append("    private global::System.Threading.CancellationToken __Retirement(global::Sunder.Sdk.Rpc.SunderRpcProviderSnapshot provider) => __selectedProvider is not null ? __providerRetirement : __lifetime.Bindings.CreateProvider<")
                .Append(ApiType(contract)).Append(">(provider, (_, snapshot, retirement) => new ").Append(name).AppendLine("(__lifetime, snapshot, __services, retirement)).RetirementToken;");
            SunderRpcCSharpImplementationEmitter.EmitServiceClientCodec(output, contract, name);
            var marshalling = SunderRpcCSharpMarshallingPlan.Owned(contract);
            marshalling.EmitConfiguration(output, sourceCodec: true);
            foreach (var method in contract.Methods.OrderBy(value => value.MethodId, StringComparer.Ordinal))
                EmitMarshalledClientMethod(output, contract, method, packageId, packageVersion, marshalling);
            output.AppendLine("    void global::System.IDisposable.Dispose() { if (__ownsLifetime) __lifetime.Dispose(); }")
                .AppendLine("    global::System.Threading.Tasks.ValueTask global::System.IAsyncDisposable.DisposeAsync() => __ownsLifetime ? __lifetime.DisposeAsync() : global::System.Threading.Tasks.ValueTask.CompletedTask;")
                .AppendLine("}");
            EmitCatalogDeclaration(output, contract.Descriptor, ApiType(contract), name + "Providers", name, imported: false);
            output.AppendLine("}");
            files.Add(new("service-clients/" + contract.ContractKey + ".g.cs", output.ToString().Replace("\r\n", "\n", StringComparison.Ordinal)));
        }
        return files;
    }

    private static void EmitClientMethod(StringBuilder output, SunderRpcCSharpCompiledContract contract, SunderRpcCSharpMethodModel method, string packageId, string packageVersion)
    {
        var names = method.Source.Parameters.Select(value => value.Name).ToHashSet(StringComparer.Ordinal);
        string Local(string value) { while (!names.Add(value)) value += "_"; return value; }
        var scope = Local("__scope"); var token = Local("__token"); var core = Local("__call");
        var api = Local("__api"); var provider = Local("__provider"); var request = Local("__request"); var response = Local("__response");
        var cancellation = method.Source.Parameters.FirstOrDefault(IsToken);
        var caller = cancellation is null ? "default" : SunderRpcCSharpSyntax.EscapeIdentifier(cancellation.Name);
        var resultType = method.ReturnsUnit ? null : ((INamedTypeSymbol)method.Source.ReturnType).TypeArguments[0];
        var result = resultType?.ToDisplayString(SignatureFormat) ?? "bool";
        var nullable = resultType?.NullableAnnotation == NullableAnnotation.Annotated || resultType is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T };
        var stream = method.Kind == "server-stream";
        output.Append("    public ").Append(stream ? "" : "async ").Append(Signature(method.Source)).AppendLine(" {");
        if (stream)
        {
            output.Append("        return this.__lifetime.Subscribe(").Append(core).Append(", ").Append(caller).AppendLine(");")
                .Append("        async global::System.Collections.Generic.IAsyncEnumerable<").Append(result).Append("> ").Append(core)
                .Append("(global::Sunder.Sdk.Rpc.ISunderRpcCallScope ").Append(scope)
                .Append(", [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken ").Append(token).AppendLine(") {");
        }
        else output.Append(method.ReturnsUnit ? "        await this.__lifetime.Invoke(async (" : "        return await this.__lifetime.Invoke(async (").Append(scope).Append(", ").Append(token).AppendLine(") => { ");
        output.Append("            var ").Append(provider).AppendLine(" = this.__selectedProvider;")
            .Append("            if (").Append(provider).AppendLine(" is null) {")
            .Append("            var ").Append(api).Append(" = new global::").Append(contract.GeneratedLogicalName).Append(".Api.Contract(").Append(scope).Append(", ")
            .Append(Literal(packageId)).Append(", ").Append(Literal("=" + packageVersion)).AppendLine(", true);")
            .Append("            ").Append(provider).Append(" = (await ").Append(api).Append(".ResolveSelectedPackageAsync(").Append(token).AppendLine(").ConfigureAwait(false)).Snapshot;")
            .Append("            if (").Append(provider).Append(".PackageVersion != ").Append(Literal(packageVersion))
            .AppendLine(") throw new global::Sunder.Sdk.Rpc.SunderRpcException(new(global::Sunder.Sdk.Rpc.SunderRpcErrorKind.StaleEndpoint, \"rpc.stale-endpoint\", \"The owning package version changed.\"));")
            .AppendLine("            }")
            .Append("            await ServiceClientLifetime.EnsureCurrent(").Append(scope).Append(", ").Append(provider).Append(", ").Append(token).AppendLine(").ConfigureAwait(false);");
        var parameters = method.Source.Parameters.Where(value => !IsContext(value) && !IsToken(value)).ToArray();
        if (parameters.Length == 1)
            output.Append("            var ").Append(request).Append(" = global::System.Text.Json.JsonSerializer.SerializeToElement<")
                .Append(parameters[0].Type.ToDisplayString(SignatureFormat)).Append(">(").Append(SunderRpcCSharpSyntax.EscapeIdentifier(parameters[0].Name)).AppendLine(", JsonOptions);");
        else
        {
            output.Append("            var ").Append(request).AppendLine(" = global::System.Text.Json.JsonSerializer.SerializeToElement(new global::System.Collections.Generic.Dictionary<string, global::System.Text.Json.JsonElement> {");
            foreach (var parameter in parameters)
            {
                if (!SunderRpcCSharpNaming.TryCreate(parameter.Name, null, out var wire)) throw new InvalidOperationException("Validated parameter has no wire name.");
                output.Append("                [").Append(Literal(wire!.Camel)).Append("] = global::System.Text.Json.JsonSerializer.SerializeToElement<")
                    .Append(parameter.Type.ToDisplayString(SignatureFormat)).Append(">(").Append(SunderRpcCSharpSyntax.EscapeIdentifier(parameter.Name)).AppendLine(", JsonOptions),");
            }
            output.AppendLine("            });");
        }
        if (stream) output.Append("            await foreach (var ").Append(response).Append(" in ").Append(scope).Append(".SubscribeAsync(");
        else output.Append("            var ").Append(response).Append(" = await ").Append(scope).Append(".InvokeAsync(");
        output.Append(provider).Append(".Endpoint, ").Append(Literal(contract.Descriptor.Services.Single().ServiceId)).Append(", ")
            .Append(Literal(method.MethodId)).Append(", ").Append(request).Append(", cancellationToken: ").Append(token)
            .AppendLine(stream ? ").ConfigureAwait(false)) {" : ").ConfigureAwait(false);")
            .Append("            await ServiceClientLifetime.EnsureCurrent(").Append(scope).Append(", ").Append(provider).Append(", ").Append(token).AppendLine(").ConfigureAwait(false);")
            .Append("            ").Append(stream ? "yield return " : "return ");
        if (method.ReturnsUnit) output.AppendLine("true;");
        else output.Append("Deserialize<").Append(result).Append(">(").Append(response)
            .Append(", allowsNull: ").Append(nullable ? "true" : "false").AppendLine(");");
        if (stream)
            output.AppendLine("            }")
                .Append("            await ServiceClientLifetime.EnsureCurrent(").Append(scope).Append(", ").Append(provider).Append(", ").Append(token).AppendLine(").ConfigureAwait(false); }");
        else output.Append("        }, ").Append(caller).AppendLine(").ConfigureAwait(false);");
        output.AppendLine("    }");
    }

    private static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);

    internal static string EmitImportedLifetime(string packageId) => EmitLifetime(packageId)
        .Replace("ServiceClientLifetime", "ImportedServiceClientLifetime", StringComparison.Ordinal)
        .Replace("GeneratedServiceProviders", "ImportedServiceProviders", StringComparison.Ordinal);

    private static string EmitLifetime(string packageId)
        => (LifetimeSource + "\n" + CatalogRuntimeSource).Replace("__SUNDER_INTERNAL_NAMESPACE__", Editor.GeneratedPackageNames.Internal(packageId), StringComparison.Ordinal) + "\n";

    private const string LifetimeSource = """
        // <auto-generated />
        #nullable enable
        using global::System;
        using global::System.Collections.Generic;
        using global::System.Threading;
        using global::System.Threading.Tasks;
        using global::Sunder.Sdk.Rpc;
        namespace __SUNDER_INTERNAL_NAMESPACE__;
        internal sealed class ServiceClientLifetime : IDisposable, IAsyncDisposable
        {
            private readonly ISunderRpcClient rpc;
            private readonly bool _ownsBindings;
            private readonly SunderRpcResourceLifetime _resources;
            internal SunderRpcServiceBindingLifetime Bindings { get; }
            internal ServiceClientLifetime(ISunderRpcClient client, SunderRpcServiceBindingLifetime? bindings = null)
            {
                rpc = client; _ownsBindings = bindings is null;
                Bindings = bindings ?? new(client);
                _resources = new(Bindings);
            }
            private readonly CancellationTokenSource _retirement = new();
            private readonly TaskCompletionSource _drained = new(TaskCreationOptions.RunContinuationsAsynchronously);
            private readonly object _gate = new();
            private bool _stopped;
            private int _active;
            private Task? _stop;
            internal ValueTask<SunderRpcMarshallingContext> CreateCallAsync(SunderRpcProviderSnapshot provider, CancellationToken caller,
                CancellationToken enumeration = default, CancellationToken providerRetirement = default, int timeoutSeconds = 0)
                => _resources.CreateCallAsync(rpc, provider.Endpoint,
                    options: timeoutSeconds == 0 ? null : new SunderRpcCallOptions(DateTimeOffset.UtcNow.AddSeconds(timeoutSeconds)),
                    cancellationToken: caller, enumerationCancellationToken: enumeration, providerRetirementToken: providerRetirement);
            internal async ValueTask<T> Query<T>(Func<ISunderRpcClient, CancellationToken, ValueTask<T>> query, CancellationToken token)
            {
                var retirement = Enter(token);
                try
                {
                    using var linked = CancellationTokenSource.CreateLinkedTokenSource(token, retirement);
                    var result = await query(rpc, linked.Token).ConfigureAwait(false);
                    linked.Token.ThrowIfCancellationRequested();
                    return result;
                }
                catch (Exception error)
                {
                    var translated = SunderRpcServiceCall.TranslateCancellation(error, token, retirementToken: retirement);
                    if (ReferenceEquals(translated, error)) throw;
                    throw translated;
                }
                finally { Exit(); }
            }
            internal async IAsyncEnumerable<T> Observe<T>(Func<ISunderRpcClient, CancellationToken, IAsyncEnumerable<T>> query,
                [global::System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken token)
            {
                var retirement = Enter(token);
                try
                {
                    using var linked = CancellationTokenSource.CreateLinkedTokenSource(token, retirement);
                    await foreach (var value in query(rpc, linked.Token).WithCancellation(linked.Token).ConfigureAwait(false))
                    { linked.Token.ThrowIfCancellationRequested(); yield return value; }
                }
                finally { Exit(); }
            }
            internal IAsyncEnumerable<T> SubscribeResource<T>(Func<ISunderRpcClient, CancellationToken, Action<CancellationToken>, CancellationToken, IAsyncEnumerable<T>> call,
                CancellationToken caller)
                => new ResourceSubscription<T>(this, call, caller);
            private readonly record struct ResourceCancellation(CancellationToken Caller, CancellationToken Enumeration);
            private sealed class ResourceSubscription<T>(ServiceClientLifetime lifetime,
                Func<ISunderRpcClient, CancellationToken, Action<CancellationToken>, CancellationToken, IAsyncEnumerable<T>> call, CancellationToken caller) : IAsyncEnumerable<T>
            {
                public IAsyncEnumerator<T> GetAsyncEnumerator(CancellationToken cancellationToken = default)
                    => lifetime.RunResource(call, new(caller, cancellationToken)).GetAsyncEnumerator();
            }
            private async IAsyncEnumerable<T> RunResource<T>(Func<ISunderRpcClient, CancellationToken, Action<CancellationToken>, CancellationToken, IAsyncEnumerable<T>> call,
                ResourceCancellation original)
            {
                var retirement = Enter(original.Caller);
                try
                {
                    // Only dispatch uses this temporary link. The generated call
                    // receives the original enumeration token separately so its
                    // resource scope can retain both originals beyond this iterator.
                    using var linked = CancellationTokenSource.CreateLinkedTokenSource(original.Caller, original.Enumeration, retirement);
                    var operation = linked.Token;
                    IAsyncEnumerator<T> iterator;
                    try
                    {
                        linked.Token.ThrowIfCancellationRequested();
                        iterator = call(rpc, original.Enumeration, value => operation = value, linked.Token).GetAsyncEnumerator();
                    }
                    catch (Exception error)
                    {
                        var translated = SunderRpcServiceCall.TranslateCancellation(error, original.Caller, original.Enumeration, operation);
                        if (ReferenceEquals(translated, error)) throw;
                        throw translated;
                    }
                    try
                    {
                        while (true)
                        {
                            bool next;
                            try
                            {
                                next = await iterator.MoveNextAsync().ConfigureAwait(false);
                                linked.Token.ThrowIfCancellationRequested();
                            }
                            catch (Exception error)
                            {
                                var translated = SunderRpcServiceCall.TranslateCancellation(error, original.Caller, original.Enumeration, operation);
                                if (ReferenceEquals(translated, error)) throw;
                                throw translated;
                            }
                            if (!next) break;
                            yield return iterator.Current;
                        }
                    }
                    finally
                    {
                        try { await iterator.DisposeAsync().ConfigureAwait(false); }
                        catch (Exception error)
                        {
                            var translated = SunderRpcServiceCall.TranslateCancellation(error, original.Caller, original.Enumeration, operation);
                            if (ReferenceEquals(translated, error)) throw;
                            throw translated;
                        }
                    }
                }
                finally { Exit(); }
            }
            internal async ValueTask<T> Invoke<T>(Func<ISunderRpcCallScope, CancellationToken, ValueTask<T>> call, CancellationToken token)
            {
                var retirement = Enter(token);
                try
                {
                    using var linked = CancellationTokenSource.CreateLinkedTokenSource(token, retirement);
                    await using var scope = await rpc.CreateCallScopeAsync(cancellationToken: linked.Token).ConfigureAwait(false);
                    var result = await call(scope, linked.Token).ConfigureAwait(false);
                    linked.Token.ThrowIfCancellationRequested();
                    return result;
                }
                finally { Exit(); }
            }
            internal async IAsyncEnumerable<T> Subscribe<T>(Func<ISunderRpcCallScope, CancellationToken, IAsyncEnumerable<T>> call,
                [global::System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken token)
            {
                var retirement = Enter(token);
                try
                {
                    using var linked = CancellationTokenSource.CreateLinkedTokenSource(token, retirement);
                    await using var scope = await rpc.CreateCallScopeAsync(cancellationToken: linked.Token).ConfigureAwait(false);
                    await foreach (var value in call(scope, linked.Token).WithCancellation(linked.Token).ConfigureAwait(false))
                    { linked.Token.ThrowIfCancellationRequested(); yield return value; }
                }
                finally { Exit(); }
            }
            internal static async ValueTask EnsureCurrent(ISunderRpcClient scope, SunderRpcProviderSnapshot previous, CancellationToken token)
            {
                token.ThrowIfCancellationRequested();
                var current = await scope.GetProviderAsync(previous.Endpoint, token).ConfigureAwait(false);
                if (previous.State != SunderRpcProviderState.Active || current is null || current.State != SunderRpcProviderState.Active || current.Endpoint != previous.Endpoint
                    || current.PackageId != previous.PackageId || current.PackageVersion != previous.PackageVersion
                    || current.ProviderId != previous.ProviderId || current.ContractId != previous.ContractId || current.ContractVersion != previous.ContractVersion
                    || current.DescriptorSha256 != previous.DescriptorSha256 || current.AbiSha256 != previous.AbiSha256
                    || current.ActivationId != previous.ActivationId || current.ActivationEpoch != previous.ActivationEpoch || current.SessionGeneration != previous.SessionGeneration)
                    throw new SunderRpcException(new(SunderRpcErrorKind.StaleEndpoint, "rpc.stale-endpoint", "The selected service activation is no longer current."));
            }
            private CancellationToken Enter(CancellationToken token)
            {
                lock (_gate)
                {
                    token.ThrowIfCancellationRequested();
                    ObjectDisposedException.ThrowIf(_stopped, this);
                    _active++; return _retirement.Token;
                }
            }
            private void Exit() { lock (_gate) if (--_active == 0 && _stopped) _drained.TrySetResult(); }
            public void Dispose() => _ = DisposeAsync();
            public ValueTask DisposeAsync()
            {
                lock (_gate)
                {
                    if (_stop is not null) return new(_stop);
                    _stopped = true;
                    if (_active == 0) _drained.TrySetResult();
                    return new(_stop = Stop());
                }
            }
            private async Task Stop()
            {
                try { await _retirement.CancelAsync().ConfigureAwait(false); }
                finally
                {
                    try { await _resources.DisposeAsync().ConfigureAwait(false); await _drained.Task.ConfigureAwait(false); }
                    finally { try { if (_ownsBindings) await Bindings.DisposeAsync().ConfigureAwait(false); } finally { _retirement.Dispose(); } }
                }
            }
        }
        """;
}
