using System.Text;
using Microsoft.CodeAnalysis;
using Sunder.Sdk.Rpc;

namespace Sunder.Package.Build.Rpc.Authoring.CSharp;

internal static partial class SunderRpcCSharpServiceApiEmitter
{
    private static readonly SymbolDisplayFormat SignatureFormat = Editor.ServiceApiSyntax.SignatureFormat;

    internal static string EmitInterfaces(IReadOnlyList<SunderRpcCSharpCompiledContract> contracts)
    {
        var output = new StringBuilder("// <auto-generated />\n#nullable enable\n");
        foreach (var contract in contracts.Where(value => value.ServiceType.TypeKind == TypeKind.Class).OrderBy(value => value.ContractKey, StringComparer.Ordinal))
        {
            Editor.ServiceApiSyntax.AppendInterface(output, contract.ServiceType,
                contract.Methods.OrderBy(value => value.MethodId, StringComparer.Ordinal).Select(method => method.Source));
        }
        return output.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private static string Signature(IMethodSymbol method)
        => Editor.ServiceApiSyntax.Signature(method);
    private static bool IsContext(IParameterSymbol parameter) => Editor.ServiceApiSyntax.IsContext(parameter);
    private static bool IsToken(IParameterSymbol parameter) => parameter.Type.ToDisplayString() == "System.Threading.CancellationToken";

    internal static bool RequiresContext(SunderRpcCSharpCompiledContract contract) => contract.Methods.Any(method => method.Source.Parameters.Any(IsContext));
    internal static bool HasLocalMethods(SunderRpcCSharpCompiledContract contract) => contract.Methods.Any(method => !method.Source.Parameters.Any(IsContext));
    internal static string ApiType(SunderRpcCSharpCompiledContract contract)
        => contract.ServiceType.ContainingNamespace.IsGlobalNamespace ? "global::I" + contract.ServiceType.Name
            : "global::" + SunderRpcCSharpSyntax.EscapeNamespace(contract.ServiceType.ContainingNamespace.ToDisplayString()) + "."
                + SunderRpcCSharpSyntax.EscapeIdentifier("I" + contract.ServiceType.Name);
    internal static string RemoteType(SunderRpcCSharpCompiledContract contract)
        => "global::Sunder.Generated.Services." + SunderRpcCSharpImportPrepass.ContractName(contract.Descriptor.ContractId) + "Client";
    internal static string LocalType(SunderRpcCSharpCompiledContract contract)
        => "global::Sunder.Generated.Services." + SunderRpcCSharpImportPrepass.ContractName(contract.Descriptor.ContractId) + "LocalService";

    internal static string EmitLocalServices(IReadOnlyList<SunderRpcCSharpCompiledContract> contracts)
    {
        var output = new StringBuilder("namespace Sunder.Generated.Services {\n");
        foreach (var contract in contracts.Where(contract => contract.ServiceType.TypeKind == TypeKind.Class && HasLocalMethods(contract)
                     && (!RequiresContext(contract) || contract.RuntimeUse is not null)).OrderBy(contract => contract.ContractKey, StringComparer.Ordinal))
        {
            var name = SunderRpcCSharpImportPrepass.ContractName(contract.Descriptor.ContractId) + "LocalService";
            output.Append("internal sealed class ").Append(name).Append("(").Append(contract.ServiceType.ToDisplayString(SignatureFormat)).Append(" implementation");
            if (RequiresContext(contract)) output.Append(", ").Append(RemoteType(contract)).Append(" remote");
            output.Append(") : ").Append(ApiType(contract)).AppendLine(" {");
            foreach (var method in contract.Methods.OrderBy(method => method.MethodId, StringComparer.Ordinal))
            {
                output.Append("    public ").Append(Signature(method.Source)).Append(" => ")
                    .Append(method.Source.Parameters.Any(IsContext) ? "this.__remote" : "this.__implementation").Append('.')
                    .Append(SunderRpcCSharpSyntax.EscapeIdentifier(method.Source.Name)).Append('(')
                    .AppendJoin(", ", method.Source.Parameters.Where(parameter => !IsContext(parameter)).Select(parameter => SunderRpcCSharpSyntax.EscapeIdentifier(parameter.Name))).AppendLine(");");
            }
            output.Append("    private readonly ").Append(contract.ServiceType.ToDisplayString(SignatureFormat)).AppendLine(" __implementation = implementation;");
            if (RequiresContext(contract)) output.Append("    private readonly ").Append(RemoteType(contract)).AppendLine(" __remote = remote;");
            output.AppendLine("}");
        }
        return output.AppendLine("}").ToString();
    }
}
