    public static string Emit(
        IReadOnlyList<SunderRpcCSharpCompiledContract> contracts,
        IReadOnlyList<SunderRpcCSharpImportedProvider>? importedProviders = null)
    {
        ArgumentNullException.ThrowIfNull(contracts);
        var registrationTypes = new HashSet<INamedTypeSymbol>(contracts.SelectMany(contract => contract.Providers)
            .Concat((importedProviders ?? []).Select(imported => imported.Provider)).Select(provider => provider.SourceType), SymbolEqualityComparer.Default);
        var output = new StringBuilder();
        output.AppendLine("// <auto-generated />")
            .AppendLine("#nullable enable")
            .AppendLine("using global::System.Threading.Tasks;");
        foreach (var contract in contracts.OrderBy(static item => item.ContractKey, StringComparer.Ordinal))
        {
            if (contract.Providers.Count != 0) EmitUnionSchemaHolder(output, contract);
            foreach (var provider in contract.Providers.OrderBy(static item => item.ProviderId, StringComparer.Ordinal))
            {
                EmitProvider(output, contract, provider, HasRegistrationBase(provider.SourceType, registrationTypes));
            }
        }
        foreach (var contract in (importedProviders ?? []).Where(item => item.SemanticAdapter is not null)
                     .Select(item => item.Surface.Contract).DistinctBy(item => item.Descriptor.Sha256).OrderBy(item => item.ContractKey, StringComparer.Ordinal))
            EmitPlatformAdapterSchema(output, contract);
        foreach (var imported in (importedProviders ?? []).OrderBy(static item => item.Surface.Key, StringComparer.Ordinal)
                     .ThenBy(static item => item.Provider.ProviderId, StringComparer.Ordinal))
        {
            if (imported.SemanticAdapter is not null)
            {
                EmitPlatformAdapter(output, imported, HasRegistrationBase(imported.Provider.SourceType, registrationTypes));
                continue;
            }
            var provider = imported.Provider;
            var contract = imported.Surface.Contract;
            var namespaceName = provider.SourceType.ContainingNamespace.IsGlobalNamespace
                ? null
                : provider.SourceType.ContainingNamespace.ToDisplayString();
            if (namespaceName is not null)
            {
                output.Append("namespace ").Append(EscapeNamespace(namespaceName)).AppendLine()
                    .AppendLine("{");
            }
            output.Append("partial class ").Append(EscapeIdentifier(provider.SourceType.Name)).AppendLine()
                .AppendLine("{")
                .Append("    public ").Append(HasRegistrationBase(provider.SourceType, registrationTypes) ? "new " : string.Empty)
                .AppendLine("global::Sunder.Sdk.Worker.SunderWorkerProviderRegistration CreateSunderRpcProviderRegistration()")
                .AppendLine("        => new(")
                .Append("            \"").Append(EscapeString(provider.ProviderId)).AppendLine("\",")
                .Append("            \"").Append(EscapeString(contract.Descriptor.ContractId)).AppendLine("\",")
                .Append("            \"").Append(EscapeString(contract.Descriptor.Version)).AppendLine("\",")
                .Append("            \"").Append(contract.Descriptor.Sha256).AppendLine("\",")
                .Append("            \"").Append(contract.Descriptor.AbiSha256).AppendLine("\",")
                .Append("            new global::").Append(EscapeNamespace(contract.GeneratedLogicalName)).Append('.')
                .Append(SunderRpcCSharpSyntax.Identifier(contract.Descriptor.ContractId)).Append("RpcHandler(")
                .Append(string.Join(", ", contract.Descriptor.Services.Select(static _ => "this")))
                .AppendLine("));");
            EmitProviderDeclaration(output, contract.Descriptor, provider.ProviderId, HasRegistrationBase(provider.SourceType, registrationTypes));
            output.AppendLine("}");
            if (namespaceName is not null)
            {
                output.AppendLine("}");
            }
            output.AppendLine();
        }
        return output.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    internal static string EmitServiceHandler(SunderRpcCSharpCompiledContract contract)
    {
        ArgumentNullException.ThrowIfNull(contract);
        var output = new StringBuilder("// <auto-generated />\n#nullable enable\nusing global::System.Threading.Tasks;\n");
        EmitUnionSchemaHolder(output, contract);
        EmitProvider(output, contract, null);
        return output.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    internal static void EmitServiceClientSchema(StringBuilder output, SunderRpcCSharpCompiledContract contract)
        => EmitUnionSchemaHolder(output, contract);

    internal static void EmitServiceClientCodec(StringBuilder output, SunderRpcCSharpCompiledContract contract, string containerName)
