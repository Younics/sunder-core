    }

    private static bool HasRegistrationBase(INamedTypeSymbol providerType, IReadOnlySet<INamedTypeSymbol> registrationTypes)
    {
        for (var parent = providerType.BaseType; parent is not null; parent = parent.BaseType)
            if (registrationTypes.Contains(parent)) return true;
        return false;
    }

