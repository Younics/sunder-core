    private static void EmitDeclaredErrors(StringBuilder output, SunderRpcContractDescriptor descriptor)
    {
        output.AppendLine("        private static readonly global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>> DeclaredErrorMap =")
            .AppendLine("            new global::System.Collections.ObjectModel.ReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>>(")
            .AppendLine("                new global::System.Collections.Generic.Dictionary<string, global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>>(global::System.StringComparer.Ordinal)")
            .AppendLine("                {");
        foreach (var service in descriptor.Services.OrderBy(static item => item.ServiceId, StringComparer.Ordinal))
        {
            output.Append("                    [\"").Append(EscapeString(service.ServiceId)).AppendLine("\"] =")
                .AppendLine("                        new global::System.Collections.ObjectModel.ReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>(")
                .AppendLine("                            new global::System.Collections.Generic.Dictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>(global::System.StringComparer.Ordinal)")
                .AppendLine("                            {");
            foreach (var method in service.Methods.OrderBy(static item => item.MethodId, StringComparer.Ordinal))
            {
                output.Append("                                [\"").Append(EscapeString(method.MethodId)).Append("\"] = ");
                if (method.Errors.Count == 0)
                {
                    output.AppendLine("global::System.Array.Empty<string>(),");
                }
                else
                {
                    output.Append("global::System.Array.AsReadOnly(new string[] { ");
                    for (var index = 0; index < method.Errors.Count; index++)
                    {
                        if (index > 0) output.Append(", ");
                        output.Append('"').Append(EscapeString(method.Errors[index])).Append('"');
                    }
                    output.AppendLine(" }),");
                }
            }
            output.AppendLine("                            }),");
        }
        output.AppendLine("                });")
            .AppendLine()
            .AppendLine("        public global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyList<string>>> DeclaredErrors")
            .AppendLine("            => DeclaredErrorMap;")
            .AppendLine();
    }

    private static void EmitUnaryDispatch(StringBuilder output, SunderRpcCSharpCompiledContract contract)
    {
        output.AppendLine("        public global::System.Threading.Tasks.ValueTask<global::System.Text.Json.JsonElement> InvokeUnaryAsync(")
            .AppendLine("            global::Sunder.Sdk.Rpc.SunderRpcInvocationContext context,")
            .AppendLine("            string serviceId,")
            .AppendLine("            string methodId,")
            .AppendLine("            global::System.Text.Json.JsonElement request,")
            .AppendLine("            global::System.Threading.CancellationToken cancellationToken = default)")
            .AppendLine("        {");
        var serviceId = contract.Descriptor.Services.Single().ServiceId;
        var unaryMethods = contract.Methods.Where(static method => method.Kind == "unary").ToArray();
        for (var index = 0; index < unaryMethods.Length; index++)
        {
            var method = unaryMethods[index];
            output.Append("            if (global::System.String.Equals(serviceId, \"").Append(EscapeString(serviceId))
                .Append("\", global::System.StringComparison.Ordinal) && global::System.String.Equals(methodId, \"")
                .Append(EscapeString(method.MethodId)).AppendLine("\", global::System.StringComparison.Ordinal))")
                .AppendLine("            {")
                .Append("                return InvokeUnary").Append(index + 1).AppendLine("Async(context, request, cancellationToken);")
                .AppendLine("            }");
        }
        output.AppendLine("            return global::System.Threading.Tasks.ValueTask.FromException<global::System.Text.Json.JsonElement>(UnknownMethod(serviceId, methodId, \"unary\"));")
            .AppendLine("        }")
            .AppendLine();

        for (var index = 0; index < unaryMethods.Length; index++)
        {
            var method = unaryMethods[index];
            output.Append("        private async global::System.Threading.Tasks.ValueTask<global::System.Text.Json.JsonElement> InvokeUnary")
                .Append(index + 1).AppendLine("Async(")
                .AppendLine("            global::Sunder.Sdk.Rpc.SunderRpcInvocationContext context,")
                .AppendLine("            global::System.Text.Json.JsonElement request,")
                .AppendLine("            global::System.Threading.CancellationToken cancellationToken)")
                .AppendLine("        {");
            if (contract.SourceTypes.Any(static type => type.Union is not null))
                output.Append("            ValidateUnionValue(request, \"#/$defs/").Append(EscapeString(method.RequestDefinition)).AppendLine("\");");
            output.Append("            var response = await ").Append(ServiceInvocation(contract, method))
                .AppendLine(".ConfigureAwait(false);");
            if (contract.SourceTypes.Any(static type => type.Union is not null))
                output.Append("            return ValidateUnionValue(global::System.Text.Json.JsonSerializer.SerializeToElement(response, JsonOptions), \"#/$defs/")
                    .Append(EscapeString(method.OutputDefinition)).AppendLine("\");");
            else output.AppendLine("            return global::System.Text.Json.JsonSerializer.SerializeToElement(response, JsonOptions);");
            output
                .AppendLine("        }")
                .AppendLine();
        }
    }

    private static void EmitStreamDispatch(StringBuilder output, SunderRpcCSharpCompiledContract contract)
    {
        output.AppendLine("        public global::System.Collections.Generic.IAsyncEnumerable<global::System.Text.Json.JsonElement> InvokeServerStreamAsync(")
            .AppendLine("            global::Sunder.Sdk.Rpc.SunderRpcInvocationContext context,")
            .AppendLine("            string serviceId,")
            .AppendLine("            string methodId,")
            .AppendLine("            global::System.Text.Json.JsonElement request,")
            .AppendLine("            global::System.Threading.CancellationToken cancellationToken = default)")
            .AppendLine("        {");
        var serviceId = contract.Descriptor.Services.Single().ServiceId;
        foreach (var method in contract.Methods.Where(static method => method.Kind == "server-stream"))
        {
            output.Append("            if (global::System.String.Equals(serviceId, \"").Append(EscapeString(serviceId))
                .Append("\", global::System.StringComparison.Ordinal) && global::System.String.Equals(methodId, \"")
                .Append(EscapeString(method.MethodId)).AppendLine("\", global::System.StringComparison.Ordinal))")
                .AppendLine("            {");
            if (contract.SourceTypes.Any(static type => type.Union is not null))
                output.Append("                ValidateUnionValue(request, \"#/$defs/").Append(EscapeString(method.RequestDefinition)).AppendLine("\");");
            output.Append("                return SerializeStream(").Append(ServiceInvocation(contract, method)).Append(", cancellationToken");
            if (contract.SourceTypes.Any(static type => type.Union is not null))
                output.Append(", \"#/$defs/").Append(EscapeString(method.OutputDefinition)).Append('"');
            output.AppendLine(");").AppendLine("            }");
        }
        output.AppendLine("            return ThrowStream(UnknownMethod(serviceId, methodId, \"server-stream\"), cancellationToken);")
            .AppendLine("        }")
            .AppendLine();
    }

    private static string ServiceInvocation(
        SunderRpcCSharpCompiledContract contract,
        SunderRpcCSharpMethodModel method)
    {
        var output = new StringBuilder()
            .Append("((")
            .Append(contract.ServiceType.ToDisplayString(TypeDisplayFormat))
            .Append(")_implementation).")
            .Append(EscapeIdentifier(method.Source.Name))
            .Append('(');
        var wireParameters = method.Source.Parameters.Where(static parameter =>
            !IsInvocationContext(parameter.Type) && !IsCancellationToken(parameter.Type)).ToArray();
        for (var index = 0; index < method.Source.Parameters.Length; index++)
        {
            if (index > 0) output.Append(", ");
            var parameter = method.Source.Parameters[index];
            if (IsInvocationContext(parameter.Type))
            {
                output.Append("context");
            }
            else if (IsCancellationToken(parameter.Type))
            {
                output.Append("cancellationToken");
            }
            else
            {
                var expression = wireParameters.Length == 1
                    ? "request"
                    : $"GetRequiredProperty(request, \"{EscapeString(WireName(parameter))}\")";
                output.Append("Deserialize<")
                    .Append(parameter.Type.ToDisplayString(TypeDisplayFormat))
                    .Append(">(")
                    .Append(expression)
                    .Append(", allowsNull: ")
                    .Append(AllowsNull(parameter.Type) ? "true" : "false")
                    .Append(')');
            }
        }
        return output.Append(')').ToString();
    }

    private static void EmitSerializationHelpers(StringBuilder output, SunderRpcCSharpCompiledContract contract)
    {
        output.AppendLine("        private static T Deserialize<T>(global::System.Text.Json.JsonElement value, bool allowsNull)")
            .AppendLine("        {")
            .AppendLine("            var result = global::System.Text.Json.JsonSerializer.Deserialize<T>(value, JsonOptions);")
            .AppendLine("            if (result is null && !allowsNull)")
            .AppendLine("            {")
            .AppendLine("                throw new global::System.InvalidOperationException(\"A validated RPC request deserialized to null.\");")
            .AppendLine("            }")
            .AppendLine("            return result!;")
            .AppendLine("        }")
            .AppendLine()
            .AppendLine("        private static global::System.Text.Json.JsonElement GetRequiredProperty(global::System.Text.Json.JsonElement request, string name)")
            .AppendLine("            => request.TryGetProperty(name, out var value)")
            .AppendLine("                ? value")
            .AppendLine("                : throw new global::System.InvalidOperationException($\"A validated RPC request is missing required property '{name}'.\");")
            .AppendLine()
            .AppendLine("        private static async global::System.Collections.Generic.IAsyncEnumerable<global::System.Text.Json.JsonElement> SerializeStream<T>(")
            .AppendLine("            global::System.Collections.Generic.IAsyncEnumerable<T> source,")
            .Append("            [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken cancellationToken");
        if (contract.SourceTypes.Any(static type => type.Union is not null)) output.Append(", string schemaReference");
        output.AppendLine(")")
            .AppendLine("        {")
            .AppendLine("            await foreach (var item in source.WithCancellation(cancellationToken).ConfigureAwait(false))")
            .AppendLine("            {");
        output.AppendLine(contract.SourceTypes.Any(static type => type.Union is not null)
                ? "                yield return ValidateUnionValue(global::System.Text.Json.JsonSerializer.SerializeToElement(item, JsonOptions), schemaReference);"
                : "                yield return global::System.Text.Json.JsonSerializer.SerializeToElement(item, JsonOptions);")
            .AppendLine("            }")
            .AppendLine("        }")
            .AppendLine()
            .AppendLine("        private static async global::System.Collections.Generic.IAsyncEnumerable<global::System.Text.Json.JsonElement> ThrowStream(")
            .AppendLine("            global::System.Exception exception,")
            .AppendLine("            [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken cancellationToken)")
            .AppendLine("        {")
            .AppendLine("            cancellationToken.ThrowIfCancellationRequested();")
            .AppendLine("            await global::System.Threading.Tasks.Task.CompletedTask;")
            .AppendLine("            throw exception;")
            .AppendLine("#pragma warning disable CS0162")
            .AppendLine("            yield break;")
            .AppendLine("#pragma warning restore CS0162")
            .AppendLine("        }")
            .AppendLine()
            .AppendLine("        private static global::System.Exception UnknownMethod(string serviceId, string methodId, string kind)")
            .AppendLine("            => new global::System.InvalidOperationException($\"RPC provider adapter does not implement {kind} method '{serviceId}/{methodId}'.\");");
    }

    private static string WireName(IParameterSymbol parameter)
        => SunderRpcCSharpNaming.TryCreate(parameter.Name, null, out var name)
            ? name!.Camel
            : throw new InvalidOperationException($"Validated RPC parameter '{parameter.Name}' has no wire name.");

    private static bool AllowsNull(ITypeSymbol type)
        => type.NullableAnnotation == NullableAnnotation.Annotated
           || type is INamedTypeSymbol named
           && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;

    private static bool IsCancellationToken(ITypeSymbol type)
        => type.Name == nameof(CancellationToken)
           && type.ContainingNamespace.ToDisplayString() == "System.Threading";

    private static bool IsInvocationContext(ITypeSymbol type)
        => type.Name == "SunderRpcInvocationContext"
           && type.ContainingNamespace.ToDisplayString() == "Sunder.Sdk.Rpc";

    private static string EscapeNamespace(string value)
        => SunderRpcCSharpSyntax.EscapeNamespace(value);

    private static string EscapeIdentifier(string value)
        => SunderRpcCSharpSyntax.EscapeIdentifier(value);

    private static string EscapeString(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true)[1..^1];
